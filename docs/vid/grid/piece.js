/* ===== THE COLD OPEN =====
   Nine tiles on the ground, half one colour and half the other, all mixed.
   OK is pressed and one of them simply gets up and swaps places with an empty
   square -- the whole model, performed, before the word prejudice is spoken. */
function COLDOPEN(U,gag){
  const M=U.M, O=Q.open, n=O.n, c=O.c, w=n*c;
  const x0=O.cx-w/2, y0=O.fy-w;
  const r=H.rng(13);
  const kind=[]; for(let i=0;i<n*n;i++) kind.push(r()<0.46?1:(r()<0.9?2:0));
  kind[4*n+4]=0;                                    // the hole it moves into
  const mover=3*n+2;
  const go=H.ease.inOut(H.clamp((gag-0.30)/0.46));
  rect(x0-4,y0-4,w+8,w+8,H.rgba(H.mix(P.bone,P.ink,0.80)));
  strokePoly([[x0-4,y0-4],[x0+w+4,y0-4],[x0+w+4,y0+w+4],[x0-4,y0+w+4]],
             H.rgba(H.mix(P.bone,P.ink,0.48)),2);
  for(let i=0;i<n*n;i++){
    if(!kind[i]||i===mover) continue;
    const cx2=x0+(i%n)*c, cy2=y0+((i/n)|0)*c;
    rect(cx2+1,cy2+1,c-2,c-2,
         H.rgba(kind[i]===1?H.mix(P.cyan,P.ink,0.10):H.mix(P.gold,P.ink,0.10)));
  }
  if(gag>0.02){
    const ax=x0+(mover%n)*c, ay=y0+((mover/n)|0)*c;
    const bx2=x0+4*c, by2=y0+4*c;
    const mx=H.lerp(ax,bx2,go), my=H.lerp(ay,by2,go)-Math.sin(go*Math.PI)*22;
    rect(Math.round(mx)+1,Math.round(my)+1,c-2,c-2,H.rgba(P.cyan));
    strokePoly([[mx,my],[mx+c-1,my],[mx+c-1,my+c-1],[mx,my+c-1]],
               H.rgba(H.mix(P.cyan,P.paper,0.40)),2);
  }
  if(SCENE)SCENE.push({x:x0-6,y:y0-30,w:w+12,h:w+36,k:'tiles'});
}
