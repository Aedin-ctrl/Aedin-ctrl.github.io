const GN=32, GEMPTY=0.10, GSEED=5, KA=2, KB=3;

function mulberry32(seed){ let a=seed>>>0;
  return function(){ a=(a+0x6D2B79F5)>>>0;
    let t=Math.imul(a^(a>>>15),1|a); t=(t+Math.imul(t^(t>>>7),61|t))^t;
    return ((t^(t>>>14))>>>0)/4294967296; }; }
function startBoard(N,emptyFrac,r){
  const g=new Int8Array(N*N), cells=[...Array(N*N).keys()];
  for(let i=cells.length-1;i>0;i--){ const j=Math.floor(r()*(i+1));
    const t=cells[i]; cells[i]=cells[j]; cells[j]=t; }
  cells.slice(Math.round(N*N*emptyFrac)).forEach((c,i)=>{ g[c]=(i%2)?1:2; });
  return g;
}
/* same-colour and occupied neighbour counts, eight-connected */
function nbr(g,N,i,me){
  const x=i%N, y=(i/N)|0; let same=0, occ=0;
  for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++){
    if(!dx&&!dy) continue;
    const nx=x+dx, ny=y+dy;
    if(nx<0||ny<0||nx>=N||ny>=N) continue;
    const v=g[ny*N+nx]; if(v){ occ++; if(v===me) same++; }
  }
  return [same,occ];
}
/* THE RULE, as a count: at least k the same -- or all of them, if there are
   fewer than k neighbours at all. That clause is what lets the narrator say
   "three of my neighbours" and have it be exactly true. */
const content=(g,N,i,me,k)=>{ const [s,o]=nbr(g,N,i,me); return s>=Math.min(k,o); };
function boardStats(g,N){
  let same=0,n=0,iso=0;
  for(let i=0;i<g.length;i++){ if(!g[i])continue; n++;
    const [s,o]=nbr(g,N,i,g[i]); same+=o?s/o:1; if(s===o) iso++; }
  return {same:same/n, iso:iso/n, n:n};
}
function runSim(N,k,emptyFrac,seed,maxRounds){
  const r=mulberry32(seed), g=startBoard(N,emptyFrac,r);
  const hist=[Int8Array.from(g)];
  /* WHO went WHERE, kept round by round. The board states alone cannot say
     that -- and without it a round is a cut between two pictures instead of
     a set of squares travelling, which is what the rule actually says
     happens. moves[i] takes hist[i] to hist[i+1]. */
  const moves=[];
  for(let round=0;round<maxRounds;round++){
    const un=[], em=[];
    for(let i=0;i<g.length;i++){
      if(!g[i]) em.push(i);
      else if(!content(g,N,i,g[i],k)) un.push(i); }
    if(!un.length) break;
    for(const a of [un,em]) for(let i=a.length-1;i>0;i--){
      const j=Math.floor(r()*(i+1)); const t=a[i]; a[i]=a[j]; a[j]=t; }
    let moved=0; const mv=[];
    for(const u of un){ const me=g[u]; let dest=-1;
      for(let q=0;q<em.length;q++){ const e=em[q];
        if(e===u||g[e]) continue;
        g[u]=0; const ok=content(g,N,e,me,k); g[u]=me;
        if(ok){ dest=e; em.splice(q,1); break; } }
      if(dest<0) continue;
      g[dest]=me; g[u]=0; em.push(u); moved++; mv.push([u,dest,me]); }
    hist.push(Int8Array.from(g)); moves.push(mv);
    if(!moved) break;
  }
  return {hist, moves, ...boardStats(g,N)};
}
/* Which squares FAIL the rule on a given board at a given k. The pass that
   runs on screen rings exactly these, so "unhappy" is never a decoration:
   it is the same predicate the engine moves on, asked again at draw time. */
const UNH=new Map();
function unhappy(cells,k){
  let m=UNH.get(cells); if(!m){ m={}; UNH.set(cells,m); }
  if(m[k]) return m[k];
  const u=new Uint8Array(cells.length);
  for(let i=0;i<cells.length;i++){
    if(cells[i]&&!content(cells,GN,i,cells[i],k)) u[i]=1; }
  return (m[k]=u);
}
