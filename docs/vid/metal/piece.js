/* ===== #005 -- WHY METAL FEELS COLDER THAN WOOD =====
   The piece. The format is cathode-lib.js; what needs both is cathode-run.js.

   The premise in the title is FALSE, which is the whole piece: in one room
   everything is at one temperature, and "cold" is a reading your skin takes of
   a rate, not of a temperature.

   Two numbers carry it, and both are computed rather than asserted:

   * CONDUCTIVITY, for how fast heat leaves. Carbon steel ~50 W/m.K, oak across
     the grain ~0.17 -- a ratio of 294, which is the "about three hundred times"
     in the narration. The bars cannot be drawn at 294:1, so they say so.
   * CONTACT TEMPERATURE, for what the nerve actually reads. Two solids pressed
     together settle at T = (e1.T1 + e2.T2)/(e1 + e2), weighted by thermal
     EFFUSIVITY -- skin ~1500, steel ~8000, wood ~400 (SI units). Skin at 33
     against a room at 20 gives 22 on the steel and 30 on the wood; against a
     sunlit 60 it gives 56 and 39. Four numbers, one formula, and the reversal
     at the end falls straight out of it.

   Effusivity, not conductivity, is what governs the FEEL -- so the piece uses
   conductivity only for the sentence about heat leaving, which is what
   conductivity means, and reads the contact temperatures off effusivity. */
