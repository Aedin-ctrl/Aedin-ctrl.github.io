/* ---- the score ---- */
function buildScore(){
  const E=[],add=(t,k,n)=>E.push({t:+t.toFixed(3),k,n});
  const w=(n,i)=>VO[n].t[i];
  add(0.05,'open');
  PTRACK.forEach(q=>{ if(q.c) add(q.t,'click'); });
  RINGS.forEach(q=>add(q.t,'click'));
  add(BEAT.RECAP.sc-0.35,'open'); add(BEAT.END.sc-0.30,'open');
  const LAST=VO.length-1;
  add(VO[LAST].z+0.30,'snap'); add(VO[LAST].z+0.52,'click'); add(VO[LAST].z+0.67,'open');
  [0,3,5,7,9,10,12,13,16,18].forEach(n=>VO[n].t.forEach((tt,i)=>add(tt,'blip',i)));
  add(VO[0].z+0.52,'snap');
  add(w(3,1),'draw');                                   // the two bars from part three
  for(let i=0;i<14;i++) add(w(5,0)+i*0.16,'knock',i%4); // the 360 slots laying out
  for(let i=0;i<10;i++) add(w(6,0)+i*0.20,'knock',i%3); // they fill
  add(w(7,0),'sub'); add(w(7,0)+0.06,'tag');            // 2.16x, cut
  add(w(8,6),'draw');                                   // one payment lifts out
  add(w(9,6),'zap'); add(w(9,6)+0.06,'tag');            // 83% interest
  for(let i=0;i<12;i++) add(w(10,5)+i*0.13,'blip',i);   // the divider walking
  add(w(11,4),'zap');                                   // 6.9%
  add(w(12,9),'zap'); add(w(12,9)+0.06,'tag');          // 29%
  add(w(13,0),'zap'); add(w(14,0),'tag');               // payment 223
  add(w(15,4),'sub'); add(w(16,6),'sub');               // early, then late
  add(w(17,5),'draw'); add(w(18,6),'zap');              // the other side
  for(const k in BEAT) if(BEAT[k].sc>0) add(BEAT[k].sc,'mos');
  const BPM=100, E8=30/BPM, FIG=[146.83,164.81,196.00,164.81,155.56,185.00,155.56,146.83];
  for(let i=0,tt=BEAT.LOAN.a;tt<VO[VO.length-2].t[0];i++,tt+=E8){
    add(tt,'note',FIG[i%FIG.length]*((i%16)<8?1:1.5));
    if(i%8===0) add(tt,'bass',FIG[0]/2);
  }
  E.sort((a,b)=>a.t-b.t); return E;
}
