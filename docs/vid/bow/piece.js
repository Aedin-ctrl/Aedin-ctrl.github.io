/* --- ONE RAY THROUGH ONE DROP, solved. Returns the polyline inside the drop
   and the outgoing direction, so the picture is the physics rather than an
   impression of it. --- */
function rayPath(cx,cy,R,n,b){
  const i=Math.asin(H.clamp(b)), r=Math.asin(H.clamp(b)/n);
  const alpha=Math.atan2(-b,-Math.sqrt(Math.max(0,1-b*b)));
  const turn=Math.PI-2*r;
  const A=[alpha,alpha+turn,alpha+2*turn];
  const pts=A.map(a=>[cx+Math.cos(a)*R, cy+Math.sin(a)*R]);
  const a2=A[2], nx=Math.cos(a2), ny=Math.sin(a2);
  let dx=pts[2][0]-pts[1][0], dy=pts[2][1]-pts[1][1];
  const dl=Math.hypot(dx,dy)||1; dx/=dl; dy/=dl;
  const sgn=(dx*ny-dy*nx)>=0?1:-1;
  return {pts:pts, out:[Math.cos(a2+sgn*i),Math.sin(a2+sgn*i)],
          dev:(2*(i-r)+turn)*180/Math.PI};
}
