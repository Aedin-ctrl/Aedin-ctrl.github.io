/* the stationary point of D(i) = 2(i-r) + k(pi-2r):  cos i = sqrt((n^2-1)/((k+1)^2-1)) */
function bowSolve(n,k){
  const ci=Math.sqrt((n*n-1)/((k+1)*(k+1)-1));
  const i=Math.acos(ci), r=Math.asin(Math.sin(i)/n);
  const D=2*(i-r)+k*(Math.PI-2*r);
  return {i:i*180/Math.PI, r:r*180/Math.PI, D:D*180/Math.PI};
}
