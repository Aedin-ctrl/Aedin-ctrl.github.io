/* the steer axis, as the two points it is drawn through plus where it meets
   the road. For the road bike that meeting point is AHEAD of the contact (so
   the contact trails behind it); for the TMS it is BEHIND. */
function steerAxis(cx,gy,kind){
  const fx=cx+L.WB/2;
  const top=[fx-16, gy-L.R-74], bot=[fx-4, gy-L.R-30];
  const dx=bot[0]-top[0], dy=bot[1]-top[1];
  const gx=bot[0]+dx*((gy-bot[1])/dy);
  // the built machine puts the contact 4 mm IN FRONT of the axis, so the axis
  // meets the road BEHIND the contact patch
  const ax = kind==='tms' ? fx-9 : gx;
  return { top:top, bot:bot, gx:Math.round(ax), contact:fx };
}
