function buildScore(){
  const E=[],add=(t,k,n)=>E.push({t:+t.toFixed(3),k,n});
  const w=(n,i)=>VO[n].t[i];
  add(0.05,'open');
  PTRACK.forEach(q=>{ if(q.c) add(q.t,'click'); });
  RINGS.forEach(q=>add(q.t,'click'));
  add(BEAT.PUSH.sc-0.35,'open'); add(BEAT.END.sc-0.30,'open');
  const LAST=VO.length-1;
  add(VO[LAST].z+0.30,'snap'); add(VO[LAST].z+0.52,'click'); add(VO[LAST].z+0.67,'open');
  [2,3,4,6,7,9,13,15].forEach(n=>VO[n].t.forEach((tt,i)=>add(tt,'blip',i)));
  add(VO[0].z+0.52,'snap');
  add(w(1,0),'knock');                                   // the push
  for(let i=0;i<3;i++) add(w(1,8)+i*0.42,'knock',i%3);   // the wobble
  add(w(2,0),'draw');
  add(w(3,7),'draw'); add(w(3,15),'sub');                // the spin, the twitch
  add(w(4,12),'draw'); add(w(4,16),'tag');               // the axis, the trail
  add(w(5,6),'zap'); add(w(5,6)+0.06,'tag');             // the machine is built
  add(w(6,0),'draw'); add(w(6,2),'sub');                 // counter-discs, cancelled
  add(w(6,9),'draw'); add(w(6,13),'tag');                // the contact slides
  add(w(7,4),'knock');                                   // it should fall over
  add(w(7,7),'draw'); add(w(7,10),'zap'); add(w(7,10)+0.06,'tag');
  add(w(8,0),'knock',2);                                 // the sideways hit
  add(w(9,1),'zap');                                     // NEITHER
  add(w(9,6),'draw'); add(w(10,0),'tag'); add(w(10,3),'tag');
  add(w(11,7),'draw');                                   // lean -> steer
  add(w(12,3),'sub'); add(w(12,7),'draw'); add(w(12,12),'draw');
  add(w(13,3),'knock');                                  // both released
  add(w(13,7),'zap'); add(w(13,7)+0.06,'tag');           // the short one lands
  add(w(14,4),'sub'); add(w(14,17),'tag');               // leans, hinged
  add(w(15,3),'zap');                                    // steering
  add(w(16,5),'knock',1); add(w(16,11),'knock',1);       // the two crossings-out
  for(const k in BEAT) if(BEAT[k].sc>0) add(BEAT[k].sc,'mos');
  const BPM=96, E8=30/BPM, FIG=[164.81,196.00,220.00,196.00,174.61,220.00,164.81,146.83];
  for(let i=0,tt=BEAT.PUSH.a;tt<VO[VO.length-2].t[0];i++,tt+=E8){
    add(tt,'note',FIG[i%FIG.length]*((i%16)<8?1:1.5));
    if(i%8===0) add(tt,'bass',FIG[0]/2);
  }
  E.sort((a,b)=>a.t-b.t); return E;
}
