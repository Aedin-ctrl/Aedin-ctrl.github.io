/* how far an inverted pendulum of length `len` has toppled after time `s`,
   released from `a0`. theta(t) = a0*cosh(t*sqrt(g/len)) -- the linearised
   solution, which is all the picture needs and is why the SHORT one wins:
   sqrt(g/len) is larger for a smaller len. */
function topple(len,s,a0){
  const w=Math.sqrt(9.81/len);
  return Math.min(Math.PI/2,(a0||0.055)*Math.cosh(w*s));
}

