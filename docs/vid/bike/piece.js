/* ===== LEAN, AS ONE FUNCTION =====
   The bicycle's lean and the trace drawn under it are read from the SAME
   function, so the picture and its own instrument cannot disagree. Positive
   is falling to the left of frame. Everything is in radians. */
function leanAt(t){
  // PUSH: shoved, wobbles twice, settles -- a decaying oscillation
  if(t<BEAT.ANSWERS.sc){
    const s=t-W(1,7); if(s<0) return 0;
    return 0.17*Math.exp(-s*0.62)*Math.cos(s*3.05);
  }
  // ROLL: struck sideways, then recovers
  if(t>=W(8,0)&&t<BEAT.NEITHER.sc){
    const s=t-W(8,0); if(s<0) return 0;
    return 0.21*Math.exp(-s*0.85)*Math.cos(s*3.4);
  }
  // HINGE: leans over, is caught by its own steering, comes back up
  if(t>=W(14,4)&&t<BEAT.END.sc){
    const s=t-W(14,4), peak=W(15,3)-W(14,4);
    if(s<peak) return 0.26*H.ease.inOut(H.clamp(s/peak));
    return 0.26*(1-H.ease.inOut(H.clamp((s-peak)/2.6)));
  }
  return 0;
}
/* the steer that lean produces -- the coupling, in px of front-wheel offset.
   It FOLLOWS the lean, which is the whole thesis: steering into the fall. */
function steerAt(t){ return Math.round(leanAt(t)*46); }

/* ===== THE MACHINE SEEN FROM BEHIND =====
   A side view cannot show a lean: leaning is rotation about the line the
   wheels roll along, which in side view points at the camera. The piece was
   built side-on and the whole subject -- it leans, it steers into the lean,
   it stands up -- was invisible, while the trace underneath it moved. The
   geometry beats keep the side view, because trail is a side-on fact. The
   BEHAVIOUR beats are drawn from behind, where a lean is a lean.

   Everything is in local coordinates measured from the tyre's contact patch,
   then rotated about it by the lean, so the machine pivots where it actually
   touches the road instead of about some point in its middle.

   HEIGHTS ARE TO SCALE and they carry the argument. The wheelbase is 0.75 m
   over 150 px, so 200 px to the metre. The steering mass sits at 387.5 mm and
   the rear-frame mass at 900 mm (SOM ch.9) -- 77 px and 180 px above the road.
   The low one is the FRONT one, which is what the narration says, and the
   first version of this drawing had them the other way round. */
const PXPM=200;                                     // px per metre
const H_STEER=0.3875, H_FRAME=0.90;                 // m, SOM ch.9
function bikeRear(cx,gy,kind,lean,steer,spin,counter){
  /* RS scales the whole rear view together. At 1.0 the machine was 98px on a
     768px frame -- technically centred, and far too small to read as a
     bicycle. Everything local is multiplied, so the mass heights stay in the
     same proportion to the wheel that the paper gives them. */
  const RS=1.30, R=34*RS, c=Math.cos(lean), sn=Math.sin(lean);
  const pt=(dx,dy)=>[Math.round(cx+dx*RS*c-dy*RS*sn), Math.round(gy+dx*RS*sn+dy*RS*c)];
  const base=kind==='tms'?P.cyan:P.bone;
  const col=H.rgba(base), dim=H.rgba(H.mix(base,P.ink,0.42));
  const ell=(dx,dy,rx,ry,cc)=>{ for(let a=0;a<360;a+=7){ const r=a*Math.PI/180;
      const q=pt(dx+Math.cos(r)*rx, dy+Math.sin(r)*ry); rect(q[0],q[1],2,2,cc); } };
  /* THE FRONT WHEEL IS FURTHER AWAY, so it sits higher and smaller -- that is
     what makes two ellipses read as a bicycle instead of one pod. How much of
     its rim you can see IS the steering, from this angle. */
  const sw=Math.min(24,5+Math.abs(steer)*0.8);
  ell(0,-R/RS-16,sw,R/RS-7,dim);
  // its fork legs, splayed down from the bars
  linePix([pt(-9,-86),pt(-sw*0.5,-R/RS-16)],dim,2);
  linePix([pt(9,-86),pt(sw*0.5,-R/RS-16)],dim,2);
  // the rear wheel, edge on, and its tyre on the road
  ell(0,-R/RS,7,R/RS,col);
  if(spin>0) for(let k=0;k<4;k++){ const a=spin+k*Math.PI/2;
    const q=pt(Math.cos(a)*6,-R/RS+Math.sin(a)*(R/RS-6));
    rect(q[0]-1,q[1]-1,3,3,dim); }
  if(counter>0) for(let k=0;k<4;k++){ const a=-spin*1.7+k*Math.PI/2;
    const q=pt(Math.cos(a)*5,-R/RS-16+Math.sin(a)*(R/RS-14));
    rect(q[0]-1,q[1]-1,3,3,H.rgba(P.red)); }
  // seat stays: a triangle down to the rear hub, which is the shape a bicycle
  // makes when you are behind it
  linePix([pt(0,-76),pt(-11,-R/RS+3)],col,2);
  linePix([pt(0,-76),pt(11,-R/RS+3)],col,2);
  linePix([pt(0,-76),pt(0,-14)],col,3);
  linePix([pt(-12,-80),pt(12,-80)],col,3);              // the saddle
  const ta=steer*0.030, bc=Math.cos(ta)*30, bs=Math.sin(ta)*11;
  linePix([pt(-bc,-94+bs),pt(bc,-94-bs)],col,3);        // the bars, turned
  const tyre=pt(0,0); rect(tyre[0]-8,tyre[1]-1,16,3,col);
  let topLocal=98;
  if(kind==='tms'){
    const fmY=H_FRAME*PXPM/RS, smY=H_STEER*PXPM/RS;
    linePix([pt(0,-76),pt(8,-fmY)],col,2);              // the mast
    const fm=pt(8,-fmY), sm=pt(-19,-smY);
    linePix([pt(-6,-88),sm],H.rgba(H.mix(P.gold,P.ink,0.4)),2);
    rect(fm[0]-11,fm[1]-8,22,16,H.rgba(P.orange));      // rear-frame mass, HIGH
    rect(sm[0]-10,sm[1]-7,20,14,H.rgba(P.gold));        // steering mass, LOW
    topLocal=fmY+16;
  }
  const corners=[pt(-42,0),pt(42,0),pt(-42,-topLocal),pt(42,-topLocal)];
  const xs=corners.map(q=>q[0]), ys=corners.map(q=>q[1]);
  const bx={x:Math.min(...xs)-6,y:Math.min(...ys)-6,
            w:Math.max(...xs)-Math.min(...xs)+12,h:gy-Math.min(...ys)+12};
  if(GBOX)GBOX.push({x:bx.x,y:bx.y,w:bx.w,h:bx.h,k:'bike'});
  if(SCENE)SCENE.push({x:bx.x,y:bx.y,w:bx.w,h:bx.h,k:'bike'});
  return {box:bx, steerW:sw};
}
