        winIcon(bk.x+10,bk.y+11,'i');
        const tx=bk.x+52;
        capLine('> Not the spin.',17,0,tx,bk.y+8,14,'#000');
        capLine('> Not the trail.',17,3,tx,bk.y+30,14,'#000');
        capLine('> A low front mass.',17,6,tx,bk.y+52,14,'#000');
