/* ===== #038 -- HOW DO YOU TALK TO A COMPUTER WITH NINETEEN KEYS? =====
   The first HOW IT WAS DONE piece. The strand's idea is that this channel's
   whole aesthetic -- a recreated computer interface -- becomes the subject,
   and its gate lines are A TASK, NOT A TOUR and THE DESIGN CONFESSES
   SOMETHING. Both are answered in GATE.md and both are in the piece: the
   viewer watches VERB 06 ENTER NOUN 62 ENTER being typed, and the thing the
   layout confesses is the whole second half.

   THE INSTRUMENT. The Apollo Guidance Computer's DSKY: three two-digit fields
   (PROG, VERB, NOUN), three five-digit signed registers, a block of status and
   caution lamps, and nineteen keys. There is no room for a word anywhere on
   it, so an entire command language of numbered verbs and nouns was built to
   fit a seven-segment display. VERB 06 NOUN 62 is "display, in decimal, the
   velocity set", and it is the sequence the piece types.

   THE LAMPS. Twelve legends, all real, from the Delco DSKY description: five
   WHITE status lamps -- UPLINK ACTY, NO ATT, STBY, KEY REL, OPR ERR -- and
   seven YELLOW caution lamps -- TEMP, GIMBAL LOCK, PROG, RESTART, TRACKER,
   ALT, VEL. ALT and VEL are landing-radar lamps, which is why this is the
   lunar module's panel and not the command module's.
   ⚠️ THE COLUMN ASSIGNMENT IS THIS RECREATION'S, NOT THE PANEL'S. At 432px the
   block is 2x6 and the real one is not; every legend on screen is real and
   their arrangement is a drawing decision, stated here so it is not mistaken
   for a claim.

   THE ALARM. 20 July 1969, about five minutes into powered descent, the DSKY
   showed program alarm 1202 -- an executive overflow: more jobs queued than
   the computer could finish in a cycle. Fred H. Martin (Intermetrics), writing
   in the Apollo 11 Lunar Surface Journal in July 1994, says the alarms
   "continued to appear at intervals of approximately 10 seconds", that the
   design "provided for overload, or loss of computer speed, by continuing to
   execute the highest priority jobs", and that lower-priority tasks such as a
   display refresh "fell off the queue". The load came from "cycle stealing"
   with the Rendezvous Radar Switch in AUTO -- the computer looking for radar
   data it had no use for during descent.

   WHAT THIS PIECE DOES NOT SAY:

   - NOT a percentage of the duty cycle. Sources give 13%, 15% and other
     figures and at least one outlet has published a correction on the framing.
     The piece gives the MECHANISM and no number.
   - NOT "a stuck switch". The switch position is what is attested; why it was
     there is not, and the piece says "in the wrong position" and stops.
   - NOT one person's design. Priority scheduling in the AGC flight software is
     the MIT Instrumentation Laboratory team's, and the piece names nobody,
     because naming one of them would be the easy and wrong thing to do.
   - NOT "the computer crashed". It did not. It shed load, restarted, kept the
     guidance running and reported that it had, which is the whole piece.
   - NOT the 1201 alarm, and not the distinction between 1201 (no VAC areas)
     and 1202 (no core sets). Both are real; one of them in ninety seconds is
     enough and the piece shows the one that is remembered.
   - NOT mission audio, names from the control room, or the fuel margin. Every
     one of those is a different piece.

   NOTHING HERE PROPAGATES, and that is the point: the library has drawn a
   Win95 window thirty seven times and has never once drawn a real machine. */
