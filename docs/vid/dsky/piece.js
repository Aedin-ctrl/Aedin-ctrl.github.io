/* ===== THE COLD OPEN =====
   The panel alone on the desktop, dark. OK is pressed, five keys light under
   a finger in sequence, and two digits appear. Nineteen keys and no words,
   performed before the sentence that says it. */
function COLDOPEN(U,gag){
  const M=U.M, O=Q.open, cx=O.cx, gy=O.fy, w=O.w, h=O.h;
  const x0=cx-w/2, y0=gy-h;
  rect(x0,y0,w,h,H.rgba(H.mix(P.bone,P.ink,0.62)));
  strokePoly([[x0,y0],[x0+w,y0],[x0+w,y0+h],[x0,y0+h]],
             H.rgba(H.mix(P.bone,P.ink,0.26)),2);
  // the two sunken fields at the top, and the keypad under them
  const fw=(w-26)/2;
  for(let i=0;i<2;i++){
    const fx=x0+9+i*(fw+8);
    rect(fx,y0+9,fw,20,H.rgba(P.ink));
    rect(fx,y0+9,fw,1,H.rgba(H.mix(P.bone,P.ink,0.68)));
    if(gag>0.52) px(i?NOUN_N:VERB_N,fx+fw-5,y0+12,20,
                    H.rgba(P.green),'right','"Silkscreen"');
  }
  const kw=(w-28)/5, kh=13;
  for(let r=0;r<4;r++)for(let c=0;c<5;c++){
    const kx=x0+9+c*(kw+2.5), ky=y0+38+r*(kh+3);
    const idx=r*5+c, lit=(gag*9>idx)&&(idx%4===1);
    rect(kx,ky,kw,kh,H.rgba(H.mix(P.bone,P.ink,lit?0.18:0.40)));
    rect(kx,ky,kw,1,H.rgba(H.mix(P.bone,P.paper,lit?0.30:0.16)));
  }
  if(SCENE)SCENE.push({x:x0-4,y:y0-4,w:w+8,h:h+8,k:'panel'});
}
/* ===== THE SHARED EXPLAINER SHELL, part 1 of 2 =====
   Every piece in this library opened with the same ~150 lines: the typing
   helpers, the caption stack, the boost table, the cold-open frame, the
   program window and the clip. Thirty-one copies of it drifted exactly the
   way honey and halloumi drifted before cathode-lib existed, which is the
   argument this file is the answer to.

   The piece supplies, from _body.js:
     COLDOPEN(U,gag)   draw the desktop object and its gag. The card, the
                       press and the myth stamp are HERE, not there.
     CAPS              [[text, sentence, word], ...] -- abridged clauses
     BOOSTS            [[sentence, word, amount, seconds], ...]
     BEATLABEL(T)      the status bar's middle segment
     WINNAME           the program window's title, through winTitle()
   ...and the beat bodies, in _beats.js, which is spliced in between this
   file and _xtail.js so it shares this function's scope.                 */
function explainer(ctx,W2,Hh,t){
  const T=Math.floor(t*12)/12, M=t;
  const mp=(a,b)=>H.clamp((M-a)/(b-a));
  const wordAt=(n,i)=>VO[n].t[i];
  const after=(n,i)=>t>=VO[n].t[i];
  const said=(n,a,b)=>{const v=VO[n];const lo=a||0,hi=(b===undefined?v.w.length:b);
    let o=[];for(let i=lo;i<hi;i++) if(t>=v.t[i]) o.push(v.w[i]);return o.join(' ');};
  let CARET=null;
  const typeLine=(n,x,y,size,col,shadow,font,a,b)=>{
    const str=said(n,a,b); const v=VO[n];
    const lo=a||0, hi=(b===undefined?v.w.length:b);
    const live=t>=v.t[lo]&&t<=v.z+0.25;
    const w=str?(shadow?pxShadow(str,x,y,size,col,shadow,null,font):px(str,x,y,size,col,null,font)):0;
    if(live) CARET={x:x+w+Math.round(size*0.35),y:y,h:size,col:col};
    return w;};
  const typeWrap=(n,x,y,size,col,shadow,font,perLine)=>{
    const ws=VO[n].w, lim=perLine||CAPCH;
    const rows=[]; let cur=[], len=0;
    ws.forEach((wd,i)=>{ if(len+wd.length+1>lim&&cur.length){rows.push(cur);cur=[];len=0;}
                         cur.push(i); len+=wd.length+1; });
    if(cur.length)rows.push(cur);
    rows.forEach((rw,k)=>
      typeLine(n,x,y+k*Math.round(size*1.5),size,col,shadow,font,rw[0],rw[rw.length-1]+1));
  };
  const capLine=(str,n,i,x,y,size,col,shadow,font,span)=>{
    if(!after(n,i)) return 0;
    const t0=VO[n].t[i], t1=t0+(span||Math.max(0.45,str.length*0.042));
    const cut=str.slice(0,Math.max(1,Math.round(H.clamp((t-t0)/(t1-t0))*str.length)));
    const w=shadow?pxShadow(cut,x,y,size,col,shadow,null,font):px(cut,x,y,size,col,null,font);
    if(t<t1+0.30) CARET={x:x+w+Math.round(size*0.35),y:y,h:size,col:col};
    return w;};
  /* The one line that centres a measured string. px(...,'center') centres the
     ADVANCE width, which is what you want; this exists so a caller that needs
     the x can have it without measuring twice. */
  const mid=(str,size,font)=>Math.round(LW/2-glyph(str,size,font||'"Silkscreen"').w/2);
  const CLICK=VO[VO.length-1].z+0.52, SHUT=CLICK+0.15;
  const LASTV=VO.length-1;

  /* ===== THE TAKEAWAY STACK -- abridged clauses, never the sentence.
     Three at a time, each typing in under the one before it and staying, the
     oldest dimming off the top, so a viewer who looks up mid-piece can see
     what has been established and a muted viewer has a running summary. ==== */
  const capStack=()=>{
    if(after(LASTV,0)) return;
    const fired=CAPS.filter(c=>after(c[1],c[2]));
    if(!fired.length) return;
    const show=fired.slice(-3);
    show.forEach((c,k)=>{
      const newest=(k===show.length-1), age=show.length-1-k;
      const y=CAPY+k*26;
      const col=newest?P.gold:H.mix(P.gold,P.ink,0.34+age*0.16);
      if(newest) capLine('· '+c[0],c[1],c[2],PX+26,y,CAPSZ,H.rgba(col),null,
                         '"VT323"',Math.max(0.5,c[0].length*0.040));
      else       px('· '+c[0],PX+26,y,CAPSZ,H.rgba(col),null,'"VT323"');
    });
  };

  let boost=1;
  for(const b of BOOSTS){ const t0=wordAt(b[0],b[1]);
    if(t>t0&&t<t0+(b[3]||0.32)) boost=b[2]; }

  const U={T:T,M:M,t:t,mp:mp,wordAt:wordAt,after:after,said:said,
           typeLine:typeLine,typeWrap:typeWrap,capLine:capLine,mid:mid,
           caret:(c)=>{CARET=c;}};
  const O=Q.open;
  const okT=VO[0].z+0.52;
  const FIRST=Object.keys(BEAT)[PIECE.part?2:1];
  const dlgOut=BEAT[FIRST].sc-0.30;
  const gag=H.clamp((M-(okT+0.72))/Math.max(0.001,(dlgOut-0.14)-(okT+0.72)));
  deskSky(T,O.ground);

  /* --- THE COLD OPEN. The object is already there, on the ground line, with
     the card above it; OK is pressed and the card closes on the press; half a
     second of nothing; then the object does its one trick. A SERIES PART has
     no card of its own -- its card asks the series question, and partCard()
     draws it LAST of the cold open, because a Win95 window is in front of the
     desktop, always. --- */
  if(T<dlgOut){
    if(!PIECE.part) mythStamp(t);
    COLDOPEN(U,gag);
    if(PIECE.part) partCard(T,M,t);
    else if(T<dlgOut-0.02&&M<okT+0.30){
      const rr=winFrame(DLG[0],DLG[1],DLG[2],DLG[3],'Good To Know Tho',true);
      winIcon(rr.x+10,rr.y+11,'?');
      INCHROME=true;
      typeWrap(0,rr.x+52,rr.y+14,16,'#000',null,'"Silkscreen"',24);
      button(rr.x+rr.w/2-32,rr.y+rr.h-28,64,20,'OK',M>=okT);
      INCHROME=false;
    }
  }

  if(T>=dlgOut&&T<SHUT){
    const done=T>=BEAT.END.sc;
    /* The program window's title bar is the STRAND badge (v4.21) -- the same
       slot a series part puts its series question in. */
    const r=winFrame(8,8,PW+8,PH+34,
                     PIECE.part?PIECE.part.series:winTitle(WINNAME),!done);
    const CX=r.x,CY=r.y,CWd=r.w,CHd=r.h-18;
    rect(CX,CY,CWd,CHd,P.ink);bevel(CX,CY,CWd,CHd,'field');
    statusBar(r,T,BEATLABEL(T));
    B.save();B.beginPath();B.rect(CX+2,CY+2,CWd-4,CHd-4);B.clip();
    /* --- THE QUEUE IS A CONVEYOR, NOT A PICTURE. The executive was taking
       jobs off the front of this thing every cycle for as long as the beat
       lasts, and in the descent more were arriving behind them than it could
       clear -- so the blocks march left at the rate the machine finishes
       them, the ones that will not fit inside one cycle hang off the
       right-hand end, and the overflow is something HAPPENING rather than a
       word. Both schedulers in SHED are the same construction, which is the
       only way the comparison means anything. --- */
    const JP=26, JW=22;
    const jobTrain=(bx,by,bw,bh,done,len,lim,paint)=>{
      const n1=Math.floor(done+len);
      for(let n=Math.max(0,Math.ceil(done)-1);n<=n1;n++){
        let x=bx+4+(n-done)*JP, w=JW;
        if(x<bx){ w=JW-(bx-x); x=bx; }        // this one is being finished
        if(w<=1||x>bx+bw+24||x+JW>bx+lim) continue;
        const c=paint(n,(x+JW>bx+bw),n-done);
        if(c) rect(Math.round(x),by+6,Math.round(w),bh-12,H.rgba(c));
      }
    };

    /* --- the panel's state. Which key is down, what is in the fields, which
       lamps are lit: every beat is one of these and nothing else. --- */
    const keyDown=()=>{
      for(let i=SEQ.length-1;i>=0;i--){
        const t0=wordAt(4,0)+0.10+i*0.46;
        if(M>=t0&&M<t0+0.22) return SEQ[i];
      }
      if(after(14,11)&&M<wordAt(14,11)+0.22) return 'RSET';
      return null;
    };
    const typed=()=>{
      let n=0;
      for(let i=0;i<SEQ.length;i++) if(M>=wordAt(4,0)+0.10+i*0.46) n=i+1;
      return n;
    };

    /* ============ LANG -- three fields, nowhere to put a word =========== */
    if(T>=BEAT.LANG.sc&&T<BEAT.TYPE.sc){
      px('DISPLAY AND KEYBOARD',Q.cx,62,14,
         H.rgba(H.mix(P.bone,P.ink,0.28)),'center','"Silkscreen"');
      dsky({M:M,prog:after(1,8)?PROG_N:'',verb:'',noun:'',
            acty:Math.sin(M*5)>0.2,regs:['','',''],lamps:[]});
      if(after(3,8)) px('VERB: WHAT TO DO',Q.cx,Q.rows[0],20,
                        H.rgba(P.green),'center','"Silkscreen"');
      if(after(3,14)) px('NOUN: WHAT TO DO IT TO',Q.cx,Q.rows[1],20,
                         H.rgba(P.green),'center','"Silkscreen"');
    }

    /* ============ TYPE -- the task, eight keystrokes =================== */
    if(T>=BEAT.TYPE.sc&&T<BEAT.ASK.sc){
      px('VERB 06  NOUN 62',Q.cx,62,20,
         H.rgba(H.mix(P.bone,P.ink,0.18)),'center','"Silkscreen"');
      const n=typed();
      dsky({M:M,prog:PROG_N,
            verb:n>=2?(n>=3?VERB_N:'0'):'',
            noun:n>=6?(n>=7?NOUN_N:'6'):'',
            acty:Math.sin(M*9)>0,
            regs:after(5,6)?REGS:['','',''],
            lamps:[], down:keyDown()});
      if(after(5,0)) px('DISPLAY, IN DECIMAL, THE VELOCITY SET',Q.cx,Q.rows[0],14,
                        H.rgba(H.mix(P.bone,P.ink,0.34)),'center','"Silkscreen"');
    }

    /* ============ ASK -- steady, or flashing =========================== */
    if(T>=BEAT.ASK.sc&&T<BEAT.ALARM.sc){
      px('ONE MORE THING IT DOES',Q.cx,62,14,
         H.rgba(H.mix(P.bone,P.ink,0.28)),'center','"Silkscreen"');
      const flash=after(7,12);
      dsky({M:M,prog:PROG_N,verb:VERB_N,noun:NOUN_N,acty:Math.sin(M*9)>0,
            regs:REGS,lamps:[],flash:flash});
      if(after(7,0)&&!flash) px('STEADY: IT IS TELLING YOU',Q.cx,Q.rows[0],20,
                                H.rgba(P.green),'center','"Silkscreen"');
      if(flash) px('FLASHING: IT IS ASKING YOU',Q.cx,Q.rows[0],20,
                   H.rgba(P.gold),'center','"Silkscreen"');
      if(after(8,4)) px('A WAY TO INTERRUPT A PILOT',Q.cx,Q.rows[1],14,
                        H.rgba(H.mix(P.bone,P.ink,0.34)),'center','"Silkscreen"');
      if(after(8,12)) px('THAT IS NOT INFORMATION',Q.cx,Q.rows[2],14,
                         H.rgba(H.mix(P.bone,P.ink,0.34)),'center','"Silkscreen"');
    }

    /* ============ ALARM -- and it did ================================== */
    if(T>=BEAT.ALARM.sc&&T<BEAT.WHY.sc){
      px(ALARM_DAY+' JULY '+ALARM_YEAR,Q.cx,62,14,
         H.rgba(H.mix(P.bone,P.ink,0.28)),'center','"Silkscreen"');
      const on=after(9,13);
      dsky({M:M,prog:PROG_N,verb:on?'05':VERB_N,noun:on?'09':NOUN_N,
            acty:Math.sin(M*9)>0,
            regs:on?['+0'+ALARM,'','']:REGS,
            lamps:on?['PROG','RESTART']:[],flash:on});
      if(after(10,0)) capLine(ALARM,10,0,U.mid(ALARM,32),Q.rows[0],32,
                              H.rgba(P.red),null,'"Silkscreen"',0.6);
    }

    /* ============ WHY -- what overflowed ============================== */
    if(T>=BEAT.WHY.sc&&T<BEAT.SHED.sc){
      px('PROGRAM ALARM '+ALARM,Q.cx,62,14,
         H.rgba(P.red),'center','"Silkscreen"');
      /* the queue: jobs arriving faster than a cycle can clear them. The bar
         is the cycle and the blocks are the jobs, so the overflow is a thing
         that happens off the end of the bar rather than a word. */
      const CY={x:46,y:150,w:340,h:46};
      px('ONE CYCLE',CY.x,CY.y-22,14,
         H.rgba(H.mix(P.bone,P.ink,0.34)),null,'"Silkscreen"');
      rect(CY.x,CY.y,CY.w,CY.h,H.rgba(H.mix(P.bone,P.ink,0.84)));
      strokePoly([[CY.x,CY.y],[CY.x+CY.w,CY.y],[CY.x+CY.w,CY.y+CY.h],
                  [CY.x,CY.y+CY.h]],H.rgba(H.mix(P.bone,P.ink,0.46)),2);
      if(GBOX)GBOX.push({x:CY.x,y:CY.y,w:CY.w,h:CY.h,k:'cyclebox'});
      /* the machine is already running when the beat opens -- it never
         stopped -- so the train is clocked off the top of the beat and not
         off a word, and the queue grows because the arrivals outrun it. */
      const u=Math.max(0,M-BEAT.WHY.sc), done=u*1.85;
      const len=Math.min(14.6,9+u*1.10);
      jobTrain(CY.x,CY.y,CY.w,CY.h,done,len,CY.w+24,
               (n,over)=>over?P.red:H.mix(P.cyan,P.ink,0.20));
      if(len>13) px('OVERFLOW',CY.x+CY.w,CY.y+CY.h+10,20,
                     H.rgba(P.red),'right','"Silkscreen"');
      // and the job that should never have been queued
      if(after(12,1)){
        const RS={x:46,y:300,w:340,h:52};
        rect(RS.x,RS.y,RS.w,RS.h,H.rgba(H.mix(P.bone,P.ink,0.80)));
        strokePoly([[RS.x,RS.y],[RS.x+RS.w,RS.y],[RS.x+RS.w,RS.y+RS.h],
                    [RS.x,RS.y+RS.h]],H.rgba(P.gold),2);
        if(GBOX)GBOX.push({x:RS.x,y:RS.y,w:RS.w,h:RS.h,k:'radarbox'});
        px('RENDEZVOUS RADAR',RS.x+12,RS.y+8,14,
           H.rgba(H.mix(P.bone,P.ink,0.22)),null,'"Silkscreen"');
        /* THE THING THAT WAS ACTUALLY HAPPENING. The switch left the radar's
           resolver running against a reference it was out of phase with, so
           it never settled -- it sent a signal that kept changing, and every
           change cost the executive a cycle. A still trace in this box would
           have been the one lie in the beat. */
        const TR=[];
        for(let x=RS.x+12;x<=RS.x+196;x+=4)
          TR.push([x,RS.y+34+Math.sin(x*0.085+M*3.1)*8
                            +Math.sin(x*0.223-M*1.9)*3.5]);
        linePix(TR,H.rgba(H.mix(P.gold,P.ink,0.28)),2);
        px(Math.sin(M*6)>0?'AUTO':'auto',RS.x+RS.w-12,RS.y+28,20,
           H.rgba(P.gold),'right','"Silkscreen"');
      }
      if(after(12,14)) px('LOOKING FOR DATA IT DID NOT NEED',Q.cx,420,14,
                          H.rgba(H.mix(P.bone,P.ink,0.34)),'center','"Silkscreen"');
    }

    /* ============ SHED -- priority, not turns ========================= */
    if(T>=BEAT.SHED.sc&&(T<BEAT.END.sc||!after(15,0))){
      px('TWO WAYS TO BE BUSY',Q.cx,62,14,
         H.rgba(H.mix(P.bone,P.ink,0.28)),'center','"Silkscreen"');
      /* Both halves of the comparison are the SAME construction -- one bar of
         jobs, one rule for what to do when it will not fit. */
      /* the row wipes in on the sentence's FIRST word, not its fourth: the
         beat opened on an empty stage and held it for a second otherwise. */
      const t1=wordAt(13,0), t2=wordAt(14,5);
      const g1=H.clamp((M-t1)/2.0), g2=H.clamp((M-t2)/2.0);
      [['IN TURN',150,g1,0,t1],['BY PRIORITY',320,g2,1,t2]].forEach(
                                                   ([lb,y,g,pri,t0])=>{
        if(g<=0) return;
        /* the row WIPES in from the left rather than appearing: a bar of
           thirteen blocks arriving between two frames was two of this
           piece's three snaps. */
        const wl=Math.round(340*H.ease.out(H.clamp(g*3)));
        px(lb,46,y-22,14,H.rgba(pri?P.green:H.mix(P.bone,P.ink,0.34)),
           null,'"Silkscreen"');
        rect(46,y,wl,46,H.rgba(H.mix(P.bone,P.ink,0.84)));
        strokePoly([[46,y],[46+wl,y],[46+wl,y+46],[46,y+46]],
                   H.rgba(pri?P.green:H.mix(P.bone,P.ink,0.46)),2);
        if(GBOX&&wl>330)GBOX.push({x:46,y:y,w:340,h:46,k:'sched'+pri+'box'});
        /* SAME CONVEYOR, TWO RULES. In turn: it clears them slowly, in
           order, and the queue runs away from it until every block in the
           bar is late. By priority: it clears them faster because it is not
           doing all of them -- the back of the queue is dropped, and the
           guidance job (every fifth one, because it is queued every cycle)
           is kept wherever in the queue it happens to be sitting. */
        const u=Math.max(0,M-t0);
        const done=u*(pri?2.35:1.15);
        const len=Math.min(14.6,9+u*1.25);
        jobTrain(46,y,340,46,done,len,wl,(n,over,slot)=>{
          if(pri) return (n%5===0)?P.green
                        :(slot>=9?H.mix(P.bone,P.ink,0.76)
                                 :H.mix(P.cyan,P.ink,0.20));
          return (len>11.5)?H.mix(P.red,P.ink,0.30):H.mix(P.cyan,P.ink,0.20);
        });
        px(pri?'LANDING KEPT':'ALL OF THEM LATE',386,y+56,14,
           H.rgba(pri?P.green:P.red),'right','"Silkscreen"');
      });
      if(after(14,16)) px('AND THEN IT TOLD YOU',Q.cx,Q.rows[1],20,
                          H.rgba(P.gold),'center','"Silkscreen"');
    }

    /* ============ END ================================================== */
    if(T>=BEAT.END.sc&&after(15,0)){
      wipeStage(CX,CY,CWd,CHd); groupBox(BX,BY,BW,BH,'DONE');
      OVERLAY=true;
      const bk=winFrame(BOX[0],BOX[1],BOX[2],BOX[3],'Good To Know Tho',true);
      winIcon(bk.x+10,bk.y+11,'i');
      const tx=bk.x+52;
      capLine('> Verbs and nouns.',15,0,tx,bk.y+8,14,'#000');
      capLine('> Flashing = asking.',15,2,tx,bk.y+30,14,'#000');
      capLine('> 1202 = overflow.',15,4,tx,bk.y+52,14,'#000');
      capLine('IT HAD',16,2,tx,bk.y+84,20,'#000080','#c0c0c0');
      capLine('ALREADY COPED',16,8,tx,bk.y+120,20,'#000080','#c0c0c0');
      button(bk.x+bk.w/2-32,bk.y+bk.h-26,64,20,'OK',t>=CLICK);
      OVERLAY=false;
    }
    capStack();
    B.restore();
  }
  endCard(T,M,SHUT,'it is now safe to','close this window.');

  /* --- the pointer. Hold, then move: sit still and make one decisive move in
     the last 0.55s before it is needed, rather than drifting across the middle
     of the diagram for the whole gap. A resting hand drifts +/-1px on two slow
     out-of-phase sines, because a frozen bitmap is not a hand. --- */
  const K2=PTRACK, APPROACH=0.70;
  let cx=K2[0].x, cy=K2[0].y, still=true;
  for(let i=0;i<K2.length;i++){
    if(M<K2[i].t){ cx=K2[Math.max(0,i-1)].x; cy=K2[Math.max(0,i-1)].y; break; }
    if(i===K2.length-1){ cx=K2[i].x; cy=K2[i].y; break; }
    if(M>=K2[i+1].t) continue;
    const seg=K2[i+1].t-K2[i].t;
    if(K2[i+1].d){ still=false;
      const e=H.ease.inOut(H.clamp((M-K2[i].t)/Math.max(0.001,seg)));
      cx=Math.round(H.lerp(K2[i].x,K2[i+1].x,e)); cy=Math.round(H.lerp(K2[i].y,K2[i+1].y,e));
    } else {
      const go=K2[i+1].t-Math.min(APPROACH,seg);
      if(M<=go){ cx=K2[i].x; cy=K2[i].y; }
      else { still=false;
        const e=H.ease.inOut(H.clamp((M-go)/Math.max(0.001,K2[i+1].t-go)));
        cx=Math.round(H.lerp(K2[i].x,K2[i+1].x,e)); cy=Math.round(H.lerp(K2[i].y,K2[i+1].y,e)); }
    }
    break;
  }
  if(still){ cx+=Math.round(Math.sin(M*1.07)); cy+=Math.round(Math.sin(M*0.73+1.3)); }
  window.pointerPos=()=>({x:cx,y:cy,caret:!!CARET});
  if(!CARET){ const S=SESSION_SPANS.find(q=>M>=q.a&&M<=q.z);
    if(S) CARET={x:S.x,y:S.y,h:S.s,col:'#ffffff'}; }
  if(CARET){ const d=M-Math.floor(M);
    if(d<0.55){ B.fillStyle=CARET.col; B.fillRect(CARET.x,CARET.y,2,CARET.h); } }

  ctx.imageSmoothingEnabled=false;
  ctx.clearRect(0,0,W2,Hh);
  ctx.drawImage(BUF,0,0,LW,LH,0,0,W2,Hh);
  glass(ctx,W2,Hh,t,boost);
}

/* ===== THE SCORE_EVENTS =====
   Every key is from the closed bank -- click snap open blip knock tag draw zap
   mos crack crumble splash sub buzz moo note bass. An invented name is simply
   a beat with no sound on it: both players wrap each event in try/catch, so
   the ONLY signal is the render printing "(1 failed)", and a render that
   prints anything but "(0 failed)" does not ship (v4.20).

   The piece supplies SCORE_EVENTS(add,w) for its own events, and MUSIC = [bpm, [the
   figure, in Hz]]. */
function buildScore(){
  const E=[],add=(t,k,n)=>E.push({t:+t.toFixed(3),k,n});
  const w=(n,i)=>VO[n].t[i];
  const LAST=VO.length-1;
  const FIRST=Object.keys(BEAT)[PIECE.part?2:1];
  add(0.05,'open');
  PTRACK.forEach(q=>{ if(q.c) add(q.t,'click'); });
  RINGS.forEach(q=>add(q.t,'click'));
  add(BEAT[FIRST].sc-0.35,'open'); add(BEAT.END.sc-0.30,'open');
  add(VO[LAST].z+0.30,'snap'); add(VO[LAST].z+0.52,'click'); add(VO[LAST].z+0.67,'open');
  // a print blip on every word of every sentence that carries a caption
  [...new Set(CAPS.map(c=>c[1]))].forEach(n=>VO[n].t.forEach((tt,i)=>add(tt,'blip',i)));
  add(VO[0].z+0.52,'snap');
  SCORE_EVENTS(add,w);
  for(const k in BEAT) if(BEAT[k].sc>0) add(BEAT[k].sc,'mos');
  const E8=30/MUSIC[0], FIG=MUSIC[1];
  for(let i=0,tt=BEAT[FIRST].sc;tt<VO[VO.length-2].t[0];i++,tt+=E8){
    add(tt,'note',FIG[i%FIG.length]*((i%16)<8?1:1.5));
    if(i%8===0) add(tt,'bass',FIG[0]/2);
  }
  E.sort((a,b)=>a.t-b.t); return E;
}
