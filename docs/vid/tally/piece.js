/* ===== #033 -- HOW DO YOU COUNT THE FISH IN A LAKE? =====
   The third HOW WOULD YOU KNOW piece, and the one that closes the strand's
   opening block. IMPOSSIBLE and INDIRECT are the strand's two gate lines and
   both are in GATE.md.

   IMPOSSIBLE. A lake cannot be drained and cannot be seen into, and the one
   number a net gives you is how many fish are in the net. Catching more does
   not converge on the answer; it measures the net harder.

   INDIRECT, and the substitution is the whole piece: you stop trying to count
   the population and measure the OVERLAP BETWEEN TWO INCOMPLETE COUNTS.

     Catch n1 fish, mark them, put them back. Catch again: n2 fish, of which
     m2 carry a mark. The marked share of the second catch estimates the
     marked share of the lake, so N = n1 * n2 / m2. This is the Lincoln-
     Petersen estimator (Petersen 1896, Lincoln 1930); the standard small-
     sample form is Chapman's, N = (n1+1)(n2+1)/(m2+1) - 1, and the piece does
     not use it because the piece's arithmetic is a demonstration, not a
     study -- see WHAT THIS PIECE DOES NOT SAY.

   THE TURN, and the reason this is not a wildlife piece. The same arithmetic
   over two lists of PEOPLE is dual-system estimation, which is how a census
   checks itself. List one is the census; list two is a Post-Enumeration
   Survey that goes back out independently. The overlap says how many were on
   neither. The US Census Bureau's 2020 PES (press release, March 2022):

     Black alone or in combination   3.30% net UNDERcount  (significant)
     Hispanic or Latino              4.99% net undercount  (significant)
     AIAN on reservations            5.64% net undercount  (significant)
     Non-Hispanic White alone        1.64% net OVERcount    (significant)
     National net coverage error    -0.24%, not statistically different from 0

   THE SECOND TURN, which is the ending. The method's one assumption is that
   the two catches are independent. For people they are not: the household a
   census misses is the household a survey misses, the two lists lean the same
   way, the overlap comes out too big and the estimated total comes out too
   SMALL. This is correlation bias, and Wachter and Freedman named the people
   it hides the FIFTH CELL -- the cell a two-by-two table has no room for.
   The check has the same blind spot as the thing it is checking.

   WHAT THIS PIECE DOES NOT SAY:

   - NOT a real mark-recapture study. 100 marked, 120 caught, 8 marked, 1500
     fish is a WORKED EXAMPLE and it is drawn as one: no lake is named, no
     date, no units beyond fish. The numbers are chosen so the arithmetic is
     exact (120/8 = 15 exactly) and so a viewer can do it in their head. The
     piece's real data is the census block, which is cited above.
   - NOT "the census was wrong by 0.24%". The national figure is not
     statistically different from zero and is not on screen. The group figures
     are, because they are significant and the Bureau says so.
   - NOT a to-scale Venn. The lens is drawn at a legible size, not at 8/120
     of anything, and the counts are labelled because of that. What IS to
     scale is the DIRECTION both turns move it: the overlap shrinking makes
     the answer bigger and the overlap growing makes it smaller, which is the
     whole of what those two beats claim.
   - NOT Chapman's correction, not variance, not three-list models. A hundred
     seconds that gestures at all three teaches none of them.
   - NOT a claim that the 2020 undercount is the fifth cell's size. Correlation
     bias means the published undercount is a FLOOR, which is what the piece
     says and all it says.

   NOTHING HERE PROPAGATES. #031 `blank` measures an unreachable thing by
   dating a different object; #032 `inside` measures one through a silence.
   This one measures a thing nobody can see by measuring how much two partial
   views of it AGREE, and the instrument is an intersection. */
