/* --- THE CHANNEL. Generated once from a seed, so the SAME path is used for
   the descent and for the return -- which is the whole point: one conductor,
   two journeys, opposite directions. A new path for the return stroke would
   be a different claim and a wrong one. --- */
function channelPath(seed,x0,y0,y1,steps){
  const r=H.rng(seed), pts=[[x0,y0]];
  let x=x0;
  for(let i=1;i<=steps;i++){
    x+=(r()-0.5)*36;
    x=Math.min(L.chhi,Math.max(L.chlo,x));
    pts.push([Math.round(x), Math.round(y0+(y1-y0)*i/steps)]);
  }
  return pts;
}
/* the branches it tries and abandons: most of them go nowhere, which is a
   fact about leaders and not decoration */
function branches(seed,path){
  const r=H.rng(seed), out=[];
  for(let i=3;i<path.length-2;i+=3){
    if(r()>0.62) continue;
    const n=2+Math.floor(r()*3), b=[path[i]];
    let x=path[i][0], y=path[i][1];
    const dir=r()<0.5?-1:1;
    for(let k=0;k<n;k++){ x+=dir*(10+r()*26); y+=12+r()*20; b.push([Math.round(x),Math.round(y)]); }
    out.push({at:i, pts:b});
  }
  return out;
}
