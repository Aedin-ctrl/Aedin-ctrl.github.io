  const w=(n,i)=>VO[n].t[i];
  add(0.05,'open');
  PTRACK.forEach(q=>{ if(q.c) add(q.t,'click'); });
  RINGS.forEach(q=>add(q.t,'click'));
  add(BEAT.DOWN.sc-0.35,'open'); add(BEAT.END.sc-0.30,'open');
  const LAST=VO.length-1;
  add(VO[LAST].z+0.30,'snap'); add(VO[LAST].z+0.52,'click'); add(VO[LAST].z+0.67,'open');
  [1,3,5,7,8,10,12,14].forEach(n=>VO[n].t.forEach((tt,i)=>add(tt,'blip',i)));
  add(VO[0].z+0.52,'snap');
  const okT=VO[0].z+0.52;
  add(okT+0.72,'draw');
  for(let i=0;i<3;i++) add(okT+0.88+i*0.12,'crack',i%3);
  add(okT+1.30,'zap'); add(okT+1.34,'crumble'); add(okT+1.92,'sub');
  add(w(1,4),'draw'); add(w(2,2),'knock',1);
  add(w(3,0),'draw');
  for(let i=0;i<8;i++) add(w(5,0)+i*0.42,'knock',i%3);
  add(w(4,10),'tag'); add(w(6,4),'sub');
  add(w(7,5),'draw');
  add(w(8,3),'zap'); add(w(8,5),'zap'); add(w(8,5)+0.06,'tag');
  add(w(9,0),'draw'); add(w(10,3),'draw');
  add(w(10,17),'zap'); add(w(10,17)+0.06,'tag');
  add(w(11,0),'draw'); add(w(11,5),'draw');
  add(w(12,5),'zap'); add(w(12,5)+0.06,'tag');
  for(let i=0;i<6;i++) add(w(14,4)+i*0.34,'blip',i%4);
  add(w(14,11),'tag'); add(w(15,5),'sub');
  for(const k in BEAT) if(BEAT[k].sc>0) add(BEAT[k].sc,'mos');
  const BPM=98, E8=30/BPM, FIG=[196.00,233.08,261.63,233.08,220.00,261.63,196.00,174.61];
