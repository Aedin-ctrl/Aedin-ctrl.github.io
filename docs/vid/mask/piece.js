/* ===== #035 -- WHAT IS ACTUALLY INSIDE AN N95? =====
   The first WHAT IS IN THIS piece. The strand's gate lines are IN YOUR HOUSE
   and ONE PART CARRIES IT; both are in GATE.md, which was written before any
   of this was drawn.

   THE OBJECT. Four layers: a spunbond outer cover, a support web, the
   melt-blown filter layer, and a spunbond inner cover. Three of them are
   structure. ONE PART CARRIES IT is the melt-blown layer and it was named in
   GATE.md before storyboarding, which is what that gate line is for.

   THE MECHANISM, and the turn. Melt-blown polypropylene fibres are a couple of
   micrometres across (one measurement of an N95 filter layer: 2.79 +/- 0.95
   um; typical melt-blown webs run 1-10 um). The particles that matter are
   smaller than the gaps between those fibres by an order of magnitude, so
   straining is not what stops them. The layer is an ELECTRET: the fibres carry
   a quasi-permanent charge put on in manufacture, and a charged fibre pulls a
   passing particle sideways out of the airstream onto itself.

   THE DEFECT, which is the reason the piece exists. A charge can be destroyed
   without a fibre moving. Grillet, Nemer, Storch, Sanchez, Piekos, Leonard,
   Hurwitz and Perkins, "COVID-19 global pandemic planning: Performance and
   electret charge of N95 respirators after recommended decontamination
   methods", Exp Biol Med 2021;246(6):740-748 (online 16 Dec 2020):

     isopropyl alcohol   reduced the surface charge by about 50%
     soap                completely neutralised the surface potential
     both                significantly reduced filtration AND failed fit
     AND                 "the loss of filtration function was not associated
                         with significant changes in the pressure drop"

   That last line is the whole piece. The check a person actually performs --
   cover it, breathe out, feel for leaks -- is a check on AIRFLOW, and airflow
   is the one property that survives. The failure is silent to the only
   instrument the wearer has.

   WHAT THIS PIECE DOES NOT SAY:

   - NOT "it is not a sieve". Mechanical capture -- interception, impaction,
     diffusion -- is real and does work. The narrator says "not MAINLY a
     sieve" and the screen says the same, because the overstatement is the
     easiest error in this subject and it is a real one.
   - NOT a number on the efficiency drop. Published figures disagree (about
     50% at 0.3 um in one 2023 study, "up to 30% loss" elsewhere, others
     unsourced). The piece gives the DIRECTION and the mechanism, and the two
     numbers it does give -- half the charge, all of the charge -- are quoted
     from one named study.
   - NOT a pore-size figure. No primary measurement of N95 media pore size was
     found to this project's standard, so the gap is drawn and never numbered.
   - NOT advice about cleaning or reusing a respirator. The piece explains an
     object; it does not tell anyone what to do with theirs.
   - NOT "washing kills it". The agents are named, and so is the study that
     found the ones that did NOT strip the charge.

   NOTHING HERE PROPAGATES. It is the library's first teardown: the object
   arrives whole, comes apart downward, and one layer out of four turns out to
   be doing all of the work by a mechanism that is not the one its shape
   suggests. */
