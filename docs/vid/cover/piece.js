/* --- THE COVER'S OWN NOTATION. Binary, written the way the cover writes it:
   a row of marks, a long one for 1 and a short one for 0, which is the thing
   a reader has to work out before any number on the plate means anything. --- */
function binary(x,y,n,bits,col,sc){
  const S=sc||1, w=3*S, gap=2*S, h=10*S;
  let v='';
  for(let i=bits-1;i>=0;i--) v+=((n>>i)&1)?'1':'0';
  for(let i=0;i<v.length;i++){
    const hh=v[i]==='1'?h:Math.round(h*0.45);
    rect(x+i*(w+gap),y+h-hh,w,hh,col);
  }
  return v.length*(w+gap);
}
