function polyReg(pts,k){
  if(!GBOX) return;
  for(let i=1;i<pts.length;i++){
    const a=pts[i-1], b=pts[i];
    GBOX.push({x:Math.min(a[0],b[0])-1,y:Math.min(a[1],b[1])-1,
               w:Math.max(2,Math.abs(b[0]-a[0]))+2,
               h:Math.max(2,Math.abs(b[1]-a[1]))+2,k:k});
  }
}
function ringPix(cx,cy,r,col,th,k){
  const n=Math.max(48,Math.round(r*2.4)), pts=[];
  for(let i=0;i<=n;i++){ const a=i/n*Math.PI*2;
    pts.push([cx+Math.cos(a)*r, cy+Math.sin(a)*r]); }
  linePix(pts,col,th||2);
  if(k&&GBOX) polyReg(pts,k);
  return pts;
}
function arcPix(cx,cy,r,d0,d1,col,th,k){
  const pts=[];
  for(let d=d0;d<=d1;d+=3){ const a=-Math.PI/2+d*Math.PI/180;
    pts.push([cx+Math.cos(a)*r, cy+Math.sin(a)*r]); }
  if(pts.length>1){ linePix(pts,col,th||3); if(k&&GBOX) polyReg(pts,k); }
  return pts;
}
