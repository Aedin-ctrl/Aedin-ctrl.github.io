/* ---- the score ---- */
function buildScore(){
  const E=[],add=(t,k,n)=>E.push({t:+t.toFixed(3),k,n});
  const w=(n,i)=>VO[n].t[i];
  add(0.05,'open');
  PTRACK.forEach(q=>{ if(q.c) add(q.t,'click'); });
  RINGS.forEach(q=>add(q.t,'click'));
  add(BEAT.SOAK.sc-0.35,'open'); add(BEAT.END.sc-0.30,'open');
  const LAST=VO.length-1;
  add(VO[LAST].z+0.30,'snap'); add(VO[LAST].z+0.52,'click'); add(VO[LAST].z+0.67,'open');
  [0,2,5,6,8,9,11,13,14,16].forEach(n=>VO[n].t.forEach((tt,i)=>add(tt,'blip',i)));
  add(VO[0].z+0.52,'snap');
  add(w(1,7),'draw');                                  // the swell
  add(w(2,5),'sub'); add(w(2,5)+0.05,'tag');           // and it is taken away
  for(let i=0;i<7;i++) add(w(3,0)+i*0.30,'knock',i%3); // the ridges counting in
  add(w(5,2),'zap'); add(w(5,2)+0.06,'tag');           // one did not
  add(w(6,4),'draw'); add(w(6,16),'zap');              // the first bar
  add(w(7,3),'draw'); add(w(7,5),'zap'); add(w(7,5)+0.06,'tag');  // and it ROSE
  for(let i=0;i<5;i++) add(w(8,0)+i*0.34,'knock',i%3); // the vessels narrowing
  add(w(9,4),'zap');                                   // the opposite of swelling
  add(w(10,4),'tag');                                  // an action
  add(w(11,0),'draw');                                 // the test
  for(let i=0;i<3;i++) add(w(13,6)+i*0.5,'knock',i);   // the grip bars
  add(w(13,16),'zap'); add(w(14,0),'sub');             // level with dry, then the null
  add(w(15,0),'draw');
  for(const k in BEAT) if(BEAT[k].sc>0) add(BEAT[k].sc,'mos');
  const BPM=100, E8=30/BPM, FIG=[146.83,164.81,196.00,164.81,155.56,185.00,155.56,146.83];
  for(let i=0,tt=BEAT.SOAK.a;tt<VO[VO.length-2].t[0];i++,tt+=E8){
    add(tt,'note',FIG[i%FIG.length]*((i%16)<8?1:1.5));
    if(i%8===0) add(tt,'bass',FIG[0]/2);
  }
  E.sort((a,b)=>a.t-b.t); return E;
}
