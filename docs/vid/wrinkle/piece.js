/* ===== #020 -- WHY YOUR FINGERS WRINKLE IN WATER =====
   The piece. The format is cathode-lib.js; what needs both is cathode-run.js.

   The folk answer is that the skin soaks up water and swells. It does soak up
   water, and that is not what makes the ridges: a finger whose sympathetic
   nerve supply is gone does not wrinkle at all, however long it sits there.

   THE CONTROL IS THE EPISODE, and it is a real one, within-subject. Hsieh,
   Huang, LiLiang, Jeng & Tsai, "Paradoxical response to water immersion in
   replanted fingers", Clinical Autonomic Research 2006 (10.1007/s10286-006-
   0340-9): twenty fingers that had been completely amputated and replanted,
   about 17.5 +- 5.2 months earlier, each measured against THE SAME PERSON'S
   matching finger on the other hand, in warm saline (0.5 mol/l NaCl, 40 C).

     normal finger     blood flow  -27.6 +- 11.5%   and the skin WRINKLED
     replanted finger  blood flow  +22.8 +- 19.6%   and the skin did NOT

   Two numbers of opposite sign out of one event, and a binary visible outcome
   beside them. That is the instrument: two fingers in the same water, and two
   bars that move in opposite directions.

   The mechanism is sympathetic VASOCONSTRICTION -- Wilder-Smith & Chow 2003
   measured the blood flow falling as the wrinkles form, reviewed in Wilder-
   Smith, "Water immersion wrinkling", Clin Auton Res 2004;14:125-131, which
   argues the volume loss produces a negative pulp pressure that pulls the
   overlying skin down. So the ridges are not swelling; they are its opposite.
   The original observation is Lewis & Pickering in the 1930s (sources give
   1935 and 1936 -- the piece says "the 1930s"), and O'Riain turned it into a
   clinical test of nerve function in 1973, which is still used.

   WHAT THE PIECE REFUSES TO DO. It does not pick a side on what wrinkling is
   FOR. Davis 2021 (PLoS ONE) found wrinkled fingers needed LESS GRIP FORCE on
   a wet object, landing about level with dry -- so the gain is against wet
   SMOOTH skin, not against dry, and the piece says it that way. A 2014 study
   of forty people found no improvement at all. Both are on screen at the end,
   together, because that is the state of the evidence. The house style's own
   gate section names this episode as the case where an open PURPOSE passes:
   the mechanism closes completely and only the why is left, in the last few
   seconds.

   Nor is this thermoregulation. #006 and #008 spent the hypothalamic set
   point and there is to be no third -- the water here is a TRIGGER, not a
   thermal load, and nothing in the piece is about managing heat.

   The trigger itself is unsettled: Wilder-Smith proposed that water entering
   through the sweat ducts shifts the local electrolyte balance, which drives
   the sympathetic response. The piece says proposed. */
