/* a fingertip, pointing up. `ridges` is a COUNT, not a texture: the piece's
   claim is that one of these has them and the other never does. */
function finger(r,ridges,tone,key,lit){
  const [fx,fy,fw,fh]=r;
  const skin=H.mix(P.earth,P.bone,tone===undefined?0.58:tone);
  const c=H.rgba(skin);
  if(GBOX)GBOX.push({x:fx,y:fy,w:fw,h:fh,k:key||'finger'});
  // the pad: a column with a domed tip
  const dome=Math.round(fw*0.5);
  rect(fx,fy+dome,fw,fh-dome,c);
  for(let i=0;i<fw;i++){
    const u=(i-fw/2)/(fw/2);
    const h2=Math.round(Math.sqrt(Math.max(0,1-u*u))*dome);
    rect(fx+i,fy+dome-h2,1,h2,c);
  }
  // the nail, so it reads as a finger and not a pill
  rect(fx+Math.round(fw*0.22),fy+Math.round(fh*0.30),Math.round(fw*0.56),
       Math.round(fh*0.26),H.rgba(H.mix(skin,P.bone,0.42)));
  // the ridges, counted in from the tip
  const n=Math.max(0,Math.round(ridges));
  for(let k=0;k<n;k++){
    const yy=fy+Math.round(dome*0.55)+k*9;
    if(yy>fy+fh-14) break;
    const inset=Math.round(6+Math.abs(k-n/2)*1.1);
    rect(fx+inset,yy,fw-inset*2,3,H.rgba(H.mix(skin,P.ink,0.46)));
    rect(fx+inset,yy+3,fw-inset*2,2,H.rgba(H.mix(skin,P.bone,0.30)));
  }
  if(lit){
    rect(fx-4,fy-4,fw+8,2,H.rgba(P.paper)); rect(fx-4,fy+fh+2,fw+8,2,H.rgba(P.paper));
    rect(fx-4,fy-4,2,fh+8,H.rgba(P.paper)); rect(fx+fw+2,fy-4,2,fh+8,H.rgba(P.paper));
  }
}
