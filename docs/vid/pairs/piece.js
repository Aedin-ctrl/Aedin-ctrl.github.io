function room(cx,cy,r,n,mesh,litA,litB){
  const pt=(i)=>[cx+Math.cos(-Math.PI/2+i/n*Math.PI*2)*r,
                 cy+Math.sin(-Math.PI/2+i/n*Math.PI*2)*r];
  if(mesh>0){
    const total=pairs(n);
    let drawn=0;
    for(let i=0;i<n;i++) for(let j=i+1;j<n;j++){
      if(drawn++/total>mesh) { i=n; break; }
      const a=pt(i), b=pt(j);
      linePix([a,b],H.rgba(H.mix(P.cyan,P.ink,0.72)),1);
    }
  }
  for(let i=0;i<n;i++){
    const p=pt(i), on=(i===litA||i===litB);
    rect(Math.round(p[0])-4,Math.round(p[1])-4,8,8,
         H.rgba(on?P.gold:H.mix(P.bone,P.ink,0.24)));
  }
  if(GBOX)GBOX.push({x:cx-r-6,y:cy-r-6,w:r*2+12,h:r*2+12,k:'room'});
  return pt;
}
