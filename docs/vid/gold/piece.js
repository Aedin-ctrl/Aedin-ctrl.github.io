/* ===== COLOUR =====
   THE ONE PLACE THIS LIBRARY LEAVES ITS PALETTE, and it has to: a piece
   about which wavelengths come back cannot draw the spectrum in five house
   colours. wl2rgb is the standard piecewise approximation to the CIE curves
   (Dan Bruton's), and every coloured pixel in the GAP and SILVER beats --
   the bar, and both swatches -- is computed from it.

   The onset is drawn as a RAMP, not a step: an interband absorption switches
   on over a range, and a hard edge would be a sharper claim than the source
   makes ("transitions which set in around 2.3 eV"). RAMP is the half-width
   of that switch-on, in nm, and it is the only number here that is a drawing
   decision rather than a measurement. */
const RAMP=34;
function wl2rgb(w){
  let r=0,g=0,b=0;
  if(w>=380&&w<440){ r=-(w-440)/60; b=1; }
  else if(w<490){ g=(w-440)/50; b=1; }
  else if(w<510){ g=1; b=-(w-510)/20; }
  else if(w<580){ r=(w-510)/70; g=1; }
  else if(w<645){ r=1; g=-(w-645)/65; }
  else if(w<=780){ r=1; }
  let f=1;
  if(w>=380&&w<420) f=0.3+0.7*(w-380)/40;
  else if(w>700&&w<=780) f=0.3+0.7*(780-w)/80;
  const G=(v)=>Math.round(255*Math.pow(Math.max(0,v)*f,0.8));
  return [G(r),G(g),G(b)];
}
/* how much of the light at w survives, given an absorption that sets in
   below (i.e. at shorter wavelength than) cut */
const survive=(w,cut)=>H.clamp((w-(cut-RAMP))/(2*RAMP));
/* The colour that comes back, WHITE-BALANCED against the light that went
   in: each channel is the reflected sum divided by the same sum with
   nothing absorbed. A metal that absorbs nothing therefore comes out
   exactly neutral, which is the point being made about silver, and gold's
   hue is what it is relative to the illuminant rather than an artefact of
   where the approximation puts its own white. */
function reflected(cut){
  let r=0,g=0,b=0, rw=0,gw=0,bw=0;
  for(let w=VIS_LO;w<=VIS_HI;w+=2){
    const c=wl2rgb(w), s=survive(w,cut);
    r+=c[0]*s; g+=c[1]*s; b+=c[2]*s;
    rw+=c[0];  gw+=c[1];  bw+=c[2];
  }
  const v=[r/(rw||1), g/(gw||1), b/(bw||1)];
  const m=Math.max(v[0],v[1],v[2])||1;
  return [v[0]/m*235, v[1]/m*235, v[2]/m*235];
}

