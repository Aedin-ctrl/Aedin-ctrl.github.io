/* ===== THE ARITHMETIC, RUN HERE =====
   Nothing below is a typed-in string. The bits come out of a DataView, the
   exact value is rebuilt as a rational with BigInt, and the decimal expansion
   is divided out -- so every digit on screen is the one the machine actually
   holds, and a change to any of it would change the frames. */
function bitsOf(x){
  const d=new DataView(new ArrayBuffer(8)); d.setFloat64(0,x);
  return (BigInt(d.getUint32(0))<<32n)|BigInt(d.getUint32(4));
}
function bitString(x){
  let s=bitsOf(x).toString(2); return s.padStart(64,'0');
}
/* THE FULL DECIMAL EXPANSION. A binary64 is m * 2^e exactly, and every binary
   fraction is a decimal fraction, so this always terminates -- which is the
   fact that makes the whole piece showable. */
function exactDecimal(x){
  const bits=bitsOf(x);
  const sign=(bits>>63n)&1n, exp=Number((bits>>52n)&0x7ffn), frac=bits&0xfffffffffffffn;
  let m,e;
  if(exp===0){ m=frac; e=-1074; } else { m=frac|(1n<<52n); e=exp-1075; }
  let s;
  if(e>=0){ s=(m<<BigInt(e)).toString(); }
  else {
    const k=-e, scaled=m*(5n**BigInt(k));
    s=scaled.toString().padStart(k+1,'0');
    s=s.slice(0,s.length-k)+'.'+s.slice(s.length-k);
    s=s.replace(/0+$/,'').replace(/\.$/,'');
  }
  return (sign?'-':'')+s;
}
/* long division, in any base: the digits of 1/d, produced rather than typed */
function expandFraction(num,den,base,n){
  let r=num%den, out='';
  for(let i=0;i<n;i++){ r*=base;
    out+=Math.floor(r/den).toString(base); r%=den; }
  return out;
}
