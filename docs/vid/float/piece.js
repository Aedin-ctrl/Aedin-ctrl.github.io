/* long division from an arbitrary digit index, in any base */
function tapeDigits(num,den,base,from,count){
  let r=num%den;
  for(let i=0;i<from;i++) r=(r*base)%den;
  let o='';
  for(let i=0;i<count;i++){ r*=base; o+=Math.floor(r/den).toString(base); r%=den; }
  return o;
}
