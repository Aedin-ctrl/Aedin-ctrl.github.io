      winIcon(bk.x+10,bk.y+11,'i');
      const tx=bk.x+52;
      capLine('> Up at the line.',13,0,tx,bk.y+8,14,'#000');
      capLine('> Down at 30.',13,2,tx,bk.y+30,14,'#000');
      capLine('> Dry on arrival.',13,4,tx,bk.y+52,14,'#000');
      capLine('AND THE BELT',14,5,tx,bk.y+88,20,'#000080','#c0c0c0');
      capLine('IS MOVING.',14,11,tx,bk.y+128,20,'#000080','#c0c0c0');
