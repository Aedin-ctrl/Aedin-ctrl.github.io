/* --- A FIELD SEEN FROM INSIDE. One function for both pictures, because they
   are the same picture: things scattered through a depth, drawn smaller and
   more numerous further away, with the near ones in front. `depth` is how far
   you are allowed to see, and pushing it out is the paradox; pulling it back
   is the answer. `trunk` draws bars (a forest), otherwise discs (stars).
   Deterministic from a seed, like everything in this format. --- */
function field(r,depth,seed,col,trunk){
  const rnd=H.rng(seed);
  /* Depth is how far you are allowed to see. Distances are sampled so that
     the FAR shells hold more of them -- which is the cancellation the FAR
     beat is about, built into the picture instead of asserted over it -- and
     everything is drawn at 1/d, so a thing twice as far is half as wide and
     half as tall and there are four times as many of them.

     The first version of this closed nowhere near: trunks stood from the
     BOTTOM of the frame at a size that collapsed with distance, so the far
     ones piled up in a strip along the floor and the top of the view stayed
     open while the caption said NO GAPS LEFT. A picture that denies its own
     caption is the #017 fault. They stand on a HORIZON now, at a height that
     still spans the view at mid distance, which is what a forest does. */
  /* How many to draw is NOT a tuned constant: it comes out of the coverage
     the depth implies. Randomly placed bars of total width `ink` across a
     view of width W leave a fraction exp(-ink/W) of it open, so to reach a
     coverage `cov` the picture needs ink = -ln(1-cov)*W. Fixed at a chosen N
     instead, the view was SOLID at the shallowest setting and the slider did
     nothing -- the instrument contradicted the sentence it was under. */
  const dmax=2+depth*26;
  const cov=Math.min(0.992,0.12+depth*0.88);
  const span=trunk?r[2]:r[2]*r[3];
  const ink=-Math.log(1-cov)*span;
  const items=[]; let tot=0, guard=0;
  while(tot<ink&&guard++<5000){
    const d=1+(dmax-1)*Math.sqrt(rnd());
    const sz=trunk?Math.max(1,Math.round(46/d)):Math.max(1,Math.round(13/d));
    items.push([d,rnd(),rnd(),sz]);
    tot+=trunk?sz:sz*sz;
  }
  items.sort((a,b)=>b[0]-a[0]);                 // far first, so near occludes
  items.forEach(([d,fx,fy,sz])=>{
    const shade=H.clamp(0.05+(d/dmax)*0.34);
    if(trunk){
      /* A SLICE through the forest: each trunk is a full-height bar whose
         WIDTH falls as 1/d, so a tree twice as far covers half as much of
         your view and there are four times as many at that distance. The
         view closes when the bars overlap, which is the whole claim and is
         the one thing this picture has to do honestly.

         Drawn with real trunk heights it did not: short far trees piled into
         a wall above the horizon with nothing under it, and the caption said
         NO GAPS LEFT over a frame that was half empty. Height is not what
         the argument is about. */
      const x=Math.round(r[0]+fx*(r[2]-sz));
      rect(x,r[1],sz,r[3],H.rgba(H.mix(col,P.ink,shade)));
    } else {
      const x=Math.round(r[0]+fx*(r[2]-sz)), y=Math.round(r[1]+fy*(r[3]-sz));
      rect(x,y,sz,sz,H.rgba(H.mix(col,P.ink,shade)));
    }
  });
  return items.length;
}
