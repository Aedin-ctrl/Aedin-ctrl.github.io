/* THE REFLECTION, SOLVED RATHER THAN SKETCHED.
   A ray straight down the centre line striking the top of a sphere comes
   straight back up: drawing it leaving sideways is a picture of something
   that cannot happen, and this beat's whole claim is that the bounce is
   REAL. So for each unexpected arrival the take-off is searched for -- the
   one bounce point on the inner core whose honest mirror reflection lands on
   THAT detector. It is a search over a fixed grid, so it is deterministic,
   and the result is cached because it cannot change between frames. */
const BOUNCE={};
function bounceTo(deg){
  if(BOUNCE[deg]) return BOUNCE[deg];
  const ep=surf(0), ri=GL.r*fINNER; let best=null;
  for(let th=1;th<=179;th+=0.25){
    const b=surf(th,ri);
    const dx=b[0]-ep[0], dy=b[1]-ep[1], L=Math.hypot(dx,dy);
    if(L<1) continue;
    const ux=dx/L, uy=dy/L;
    const nx=(b[0]-GL.cx)/ri, ny=(b[1]-GL.cy)/ri, dn=ux*nx+uy*ny;
    if(dn>-0.02) continue;                       // must strike the front face
    const rx=ux-2*dn*nx, ry=uy-2*dn*ny;          // mirror about the normal
    const fx=b[0]-GL.cx, fy=b[1]-GL.cy, fu=fx*rx+fy*ry;
    const t=-fu+Math.sqrt(Math.max(0,fu*fu-(fx*fx+fy*fy)+GL.r*GL.r));
    const ex=b[0]+rx*t, ey=b[1]+ry*t;
    let dg=Math.atan2(ey-GL.cy,ex-GL.cx)*180/Math.PI+90;
    if(dg<0) dg+=360; if(dg>180) dg=360-dg;
    const err=Math.abs(dg-deg);
    if(!best||err<best.err) best={err:err,p:[[ep[0],ep[1]],b,[ex,ey]]};
  }
  return (BOUNCE[deg]=best.p);
}
