/* ---- the score ---- */
function buildScore(){
  const E=[],add=(t,k,n)=>E.push({t:+t.toFixed(3),k,n});
  const w=(n,i)=>VO[n].t[i];
  add(0.05,'open');
  PTRACK.forEach(q=>{ if(q.c) add(q.t,'click'); });
  RINGS.forEach(q=>add(q.t,'click'));
  add(BEAT.RECAP.sc-0.35,'open'); add(BEAT.END.sc-0.30,'open');
  const LAST=VO.length-1;
  add(VO[LAST].z+0.30,'snap'); add(VO[LAST].z+0.52,'click'); add(VO[LAST].z+0.67,'open');
  [0,2,4,5,8,9,11,13,14,17].forEach(n=>VO[n].t.forEach((tt,i)=>add(tt,'blip',i)));
  add(VO[0].z+0.52,'snap');
  add(w(2,3),'draw');                                   // the mismatched bars
  for(let i=0;i<5;i++) add(w(4,0)+i*0.26,'knock',i);    // deposits crossing over
  for(let i=0;i<4;i++) add(w(5,0)+i*0.30,'knock',i);    // four paid, then nothing
  add(w(5,6),'sub'); add(w(5,6)+0.05,'tag');            // the cash runs out
  add(w(6,8),'draw');                                   // the frame forks
  add(w(7,0),'zap'); add(w(8,0),'sub');                 // fine / gone
  add(w(9,6),'tag');                                    // both are stable
  add(w(11,8),'draw'); add(w(11,16),'zap'); add(w(11,16)+0.06,'tag');
  add(w(12,4),'draw');
  add(w(13,6),'draw'); add(w(13,11),'sub');             // the bigger vault fails
  add(w(14,4),'zap'); add(w(14,4)+0.06,'tag');          // the promise lands
  for(let i=0;i<8;i++) add(w(15,1)+i*0.14,'blip',i);    // the queue dissolving
  for(let i=0;i<5;i++) add(w(17,0)+i*0.52,'knock',i%3); // the five objects
  for(const k in BEAT) if(BEAT[k].sc>0) add(BEAT[k].sc,'mos');
  const BPM=100, E8=30/BPM, FIG=[146.83,164.81,196.00,164.81,155.56,185.00,155.56,146.83];
  for(let i=0,tt=BEAT.GAP.a;tt<VO[VO.length-2].t[0];i++,tt+=E8){
    add(tt,'note',FIG[i%FIG.length]*((i%16)<8?1:1.5));
    if(i%8===0) add(tt,'bass',FIG[0]/2);
  }
  E.sort((a,b)=>a.t-b.t); return E;
}
