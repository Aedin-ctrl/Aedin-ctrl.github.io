/* ---- the score: built from the same word onsets the picture uses ---- */
function buildScore(){
  const E=[],add=(t,k,n)=>E.push({t:+t.toFixed(3),k,n});
  const w=(n,i)=>VO[n].t[i];
  add(0.05,'open');
  PTRACK.forEach(q=>{ if(q.c) add(q.t,'click'); });
  RINGS.forEach(q=>add(q.t,'click'));
  add(BEAT.RAISE.sc-0.35,'open'); add(BEAT.END.sc-0.30,'open');
  const LAST=VO.length-1;
  add(VO[LAST].z+0.30,'snap'); add(VO[LAST].z+0.52,'click'); add(VO[LAST].z+0.67,'open');
  [0,2,5,7,10,12,13,14].forEach(n=>VO[n].t.forEach((tt,i)=>add(tt,'blip',i)));
  // the gag: the press, the dial clicking up, then the same rattle as part one
  const ok=VO[0].z+0.52, bit=ok+0.72, turn=bit+0.40;
  add(ok,'snap');
  [0.02,0.14,0.26,0.38].forEach((d,i)=>add(bit+d,'click',i));  // the dial stepping
  add(turn,'sub');
  for(let i=0;i<10;i++) add(turn+0.06+i*0.075,'knock',i%4);     // the shivering
  add(turn+0.30,'mos');
  // RAISE -- the target hauled up
  add(w(2,3),'draw'); add(w(2,10),'tag');
  // GAP -- the shaded gap, then the skin clamping
  add(w(3,4),'zap'); add(w(5,0),'draw');
  // SHAKE -- the blanket
  add(w(6,0),'zap'); add(w(7,2),'draw'); add(w(7,16),'tag');
  // WHY -- the two chevrons
  add(w(9,1),'draw'); add(w(9,7),'draw'); add(w(9,15),'tag');
  // BREAK -- the dial home, and the sweat
  add(w(11,2),'zap'); add(w(11,4),'draw'); add(w(12,0),'draw');
  for(const k in BEAT) if(BEAT[k].sc>0) add(BEAT[k].sc,'mos');
  const BPM=112, E8=30/BPM, FIG=[196.00,246.94,293.66,246.94,261.63,329.63,261.63,246.94];
  for(let i=0,tt=BEAT.RAISE.a;tt<VO[VO.length-2].t[0];i++,tt+=E8){
    add(tt,'note',FIG[i%FIG.length]*((i%16)<8?1:1.5));
    if(i%8===0) add(tt,'bass',FIG[0]/2);
  }
  E.sort((a,b)=>a.t-b.t); return E;
}
