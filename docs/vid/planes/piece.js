/* Wald's equation 26 reduces to  SUM_{j>=1} a_j/q^j = 1 - a_0.
   He solved it by Birge-Vieta ("Marchant Method No. 225") and gives q = .851.
   Bisection here, so the number on screen is computed and not typed. */
const QS=(()=>{
  const f=q=>{ let s=0; for(let j=1;j<AA.length;j++) s+=AA[j]/Math.pow(q,j);
               return s-(1-AA[0]); };
  let lo=0.5, hi=0.999;
  for(let i=0;i<200;i++){ const m=(lo+hi)/2; if(f(lo)*f(m)<=0) hi=m; else lo=m; }
  return (lo+hi)/2;
})();
const PK=1-QS;                                  // .1490 -- a hit downs a plane

/* x_i: the share of ALL planes downed by their i-th hit (Wald eq 9). */
const XS=(()=>{ const out=[]; let cum=0;
  for(let i=1;i<=5;i++){ let sa=0; for(let j=0;j<i;j++) sa+=AA[j];
    const xi=PK*(1-sa-cum); out.push(xi); cum+=xi; }
  return out; })();

/* The per-hit death counts actually printed. Largest-remainder, so the four
   numbers the narrator reads out are guaranteed to sum to the 20 planes that
   did not come home -- rounding each independently happens to work here, and
   "happens to" is not a reason. */
const XN=(()=>{
  const raw=XS.map(x=>x*NPL), fl=raw.map(Math.floor);
  let rem=LOST-fl.reduce((s,v)=>s+v,0);
  const ord=raw.map((v,i)=>[v-fl[i],i]).sort((p,q)=>q[0]-p[0]);
  const out=fl.slice();
  for(let k=0;k<ord.length&&rem>0;k++,rem--) out[ord[k][1]]++;
  return out; })();

