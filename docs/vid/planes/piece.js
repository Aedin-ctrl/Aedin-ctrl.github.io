/* Where a hole may land: the wing, the rear fuselage or the tailplane, and
   never a nacelle or the cockpit. It ASKS the geometry above rather than
   restating it, so the two cannot drift apart. */
function onPlane(x,y,r){
  const [bx,by,bw,bh]=r, cx=bx+bw/2, wy=wingY(r), hs=Math.round(bw/2);
  const i=x-cx, f=Math.abs(i)/hs;
  if(Math.abs(i)<=11 && y<by+24) return false;
  for(let k=0;k<4;k++){
    const ex=engX(r,k), lead=wy+Math.round(11*Math.abs(ex-cx)/hs);
    if(Math.abs(x-ex)<11 && y>lead-19 && y<lead+11) return false;
  }
  const wl=wy+Math.round(11*f);
  if(Math.abs(i)<=hs-6 && y>=wl+3 && y<=wl+Math.round(27-17*f)-3) return true;
  if(Math.abs(i)<=6 && y>by+bh*0.56 && y<by+bh-38) return true;
  const ht=Math.round(bw*0.22), ft=Math.abs(i)/ht;
  if(Math.abs(i)<=ht-4){
    const tl=by+bh-27+Math.round(5*ft);
    if(y>=tl+2 && y<=tl+Math.round(14-7*ft)-2) return true;
  }
  return false;
}
