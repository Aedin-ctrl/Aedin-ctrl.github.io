        rect(78,288,276,96,H.rgba(H.mix(P.ink,P.bone,0.09)));
        if(GBOX)GBOX.push({x:78,y:288,w:276,h:96,k:'folkbox'});
        const lbl='IT DRIED OUT';
        const lw=glyph(lbl,20,'"Silkscreen"').w;          // measured in the draw
        px(lbl,L.cx,302,20,H.rgba(H.mix(P.bone,P.ink,0.22)),'center','"Silkscreen"');
