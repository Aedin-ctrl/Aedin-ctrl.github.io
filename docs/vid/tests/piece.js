  if(GBOX)GBOX.push({x:Bb.x0,y:Bb.y,w:full,h:Bb.h,k:'posbar'});
  // the whole bar first, then the ill share cut into its left end
  B.fillStyle=H.rgba(H.mix(P.ice,P.ink,0.50));
