/* ===== #013 -- WHY A 99%-ACCURATE TEST GETS IT WRONG =====
   The piece. The format is cathode-lib.js; what needs both is cathode-run.js.

   The folk answer is that a 99% accurate test is right 99% of the time. It is
   not: "99% accurate" is a property of the TEST, and the question "am I ill?"
   is a property of the test AND of how common the illness is. The second one
   is the number nobody is given.

   Every number here is arithmetic, not an illustration, and all of it is
   checked in this file's own constants:

   * ACCURACY. 99%, applied BOTH ways -- it catches 99 of 100 who have it and
     clears 99 of 100 who do not. Real tests publish sensitivity and
     specificity separately and they differ; the piece says "both ways" out
     loud rather than quietly assuming it.
   * SCREENING. Prior 1 in 10,000, a million tested: 100 ill, 99 of them found,
     and 1% of the other 999,900 -- 9,999 people -- told they are positive. So
     10,098 positives of which 99 are ill: 0.98%, which the piece calls "about
     one per cent".
   * SYMPTOMS. The same test, prior 1 in 10, a thousand tested: 99 found, 9
     false. 99 of 108 = 91.7%, which the piece calls "about ninety two".
   * THE CROSSOVER. At a prior of exactly 1 in 100 the two numbers are 99 and
     99 -- a true coin flip. That is not a chosen illustration, it falls out of
     the arithmetic: at accuracy a, the stacks are equal when the prior is
     (1-a), i.e. 1 in 100 at 99%.

   The three instruments are deliberately different, because the quantities
   are: a SPLIT BAR for 99-against-9,999 (a ratio no cube chart can draw --
   one cube against a hundred), the SAME BAR redrawn at the symptomatic prior
   so the comparison is the content, and TWO VOXEL STACKS at the crossover,
   which is the one moment the two amounts are comparable and the one chart
   that should be cubes. #010's hundred-dot grid is NOT reused. */
