function buildScore(){
  const E=[],add=(t,k,n)=>E.push({t:+t.toFixed(3),k,n});
  const w=(n,i)=>VO[n].t[i];
  add(0.05,'open');
  PTRACK.forEach(q=>{ if(q.c) add(q.t,'click'); });
  RINGS.forEach(q=>add(q.t,'click'));
  add(BEAT.RECAP.sc-0.35,'open'); add(BEAT.END.sc-0.30,'open');
  const LAST=VO.length-1;
  add(VO[LAST].z+0.30,'snap'); add(VO[LAST].z+0.52,'click'); add(VO[LAST].z+0.67,'open');
  [0,3,6,7,8,10,13,14,15,17].forEach(n=>VO[n].t.forEach((tt,i)=>add(tt,'blip',i)));
  add(VO[0].z+0.52,'snap');
  add(w(3,4),'draw'); add(w(3,9),'zap');              // the rows collapse into $
  for(let i=0;i<12;i++) add(w(4,10)+i*0.09,'knock',i%3);
  add(w(5,2),'draw');                                 // the frame splits
  add(w(6,0),'sub'); add(w(6,4),'zap'); add(w(6,4)+0.06,'tag');
  add(w(7,5),'zap');                                  // it is the same loaf
  add(w(9,6),'tag');                                  // the basket clamped
  for(let i=0;i<10;i++) add(w(10,3)+i*0.22,'knock',i%4);
  for(let i=0;i<6;i++)  add(w(11,0)+i*0.18,'knock',i%3);
  add(w(12,9),'sub'); add(w(12,13),'zap');            // the swap, and the index moves
  add(w(14,6),'draw'); add(w(14,10),'zap'); add(w(14,10)+0.06,'tag');
  add(w(15,6),'draw'); add(w(15,8),'zap');
  add(w(17,4),'draw'); add(w(17,9),'tag');
  for(const k in BEAT) if(BEAT[k].sc>0) add(BEAT[k].sc,'mos');
  const BPM=100, E8=30/BPM, FIG=[146.83,164.81,196.00,164.81,155.56,185.00,155.56,146.83];
  for(let i=0,tt=BEAT.ASK.a;tt<VO[VO.length-2].t[0];i++,tt+=E8){
    add(tt,'note',FIG[i%FIG.length]*((i%16)<8?1:1.5));
    if(i%8===0) add(tt,'bass',FIG[0]/2);
  }
  E.sort((a,b)=>a.t-b.t); return E;
}
