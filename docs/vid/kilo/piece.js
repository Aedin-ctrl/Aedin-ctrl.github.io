function buildScore(){
  const E=[],add=(t,k,n)=>E.push({t:+t.toFixed(3),k,n});
  const w=(n,i)=>VO[n].t[i];
  add(0.05,'open');
  PTRACK.forEach(q=>{ if(q.c) add(q.t,'click'); });
  RINGS.forEach(q=>add(q.t,'click'));
  add(BEAT.LUMP.sc-0.35,'open'); add(BEAT.END.sc-0.30,'open');
  const LAST=VO.length-1;
  add(VO[LAST].z+0.30,'snap'); add(VO[LAST].z+0.52,'click'); add(VO[LAST].z+0.67,'open');
  [2,4,5,6,9,11,13,14].forEach(n=>VO[n].t.forEach((tt,i)=>add(tt,'blip',i)));
  add(VO[0].z+0.52,'snap');
  const okT=VO[0].z+0.52;
  add(okT+0.72,'draw'); add(okT+1.24,'crumble'); add(okT+1.90,'sub');
  for(let k=0;k<3;k++) add(w(2,7)+k*0.5,'knock',k);
  add(w(4,0),'sub'); add(w(4,1),'zap');
  for(let i=0;i<NCOPIES;i++) add(w(5,7)+i*0.26,'knock',i%3);
  add(w(6,0),'draw'); add(w(6,8),'tag'); add(w(7,2),'sub');
  add(w(8,1),'zap'); add(w(8,3),'zap'); add(w(8,3)+0.06,'tag');
  add(w(9,0),'draw'); add(w(9,11),'tag');
  add(w(11,8),'draw'); add(w(11,20),'draw');
  add(w(11,29),'zap'); add(w(11,29)+0.06,'tag');
  add(w(12,6),'crumble'); add(w(13,9),'draw');
  add(w(14,10),'knock',1);
  for(const k in BEAT) if(BEAT[k].sc>0) add(BEAT[k].sc,'mos');
  const BPM=90, E8=30/BPM, FIG=[138.59,164.81,185.00,164.81,155.56,185.00,138.59,123.47];
  for(let i=0,tt=BEAT.LUMP.sc;tt<VO[VO.length-2].t[0];i++,tt+=E8){
    add(tt,'note',FIG[i%FIG.length]*((i%16)<8?1:1.5));
    if(i%8===0) add(tt,'bass',FIG[0]/2);
  }
  E.sort((a,b)=>a.t-b.t); return E;
}
