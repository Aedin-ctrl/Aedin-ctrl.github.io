/* ===== #009 -- WHY YOU CAN SEE THROUGH GLASS =====
   The piece. The format is cathode-lib.js; what needs both is cathode-run.js.

   The folk answer is that glass has gaps in it and light slips through them.
   Glass is a dense solid -- 2.5 g/cm3 against aluminium's 2.7 -- and light
   does not slip through anything. It is simply never absorbed, because
   absorbing a photon means handing its exact energy to an electron, and in
   glass there is no jump that size available to take it.

   Four numbers carry it, and every one of them is a real measured quantity
   rather than an illustration:

   * DENSITY. Soda-lime glass 2.5 g/cm3, aluminium 2.70. The bars are drawn
     from those two numbers, which is why they come out almost equal -- that
     near-equality IS the refutation of "gaps".
   * THE ABSORPTION EDGE. Ordinary window glass stops absorbing somewhere
     around 320 nm. Not the 9 eV band gap of pure fused silica: window glass
     is soda-lime, and its edge sits far lower. The piece uses the edge of the
     glass people actually look through.
   * VISIBLE LIGHT. 400 to 700 nm -- entirely on the transparent side of 320.
   * UVB. 280 to 315 nm -- entirely on the absorbed side, which is exactly why
     you do not get sunburn through a closed window, and why you still can get
     some UVA through one. The script says "burn", not "tan", for that reason.

   The spectrum axis is drawn in nanometres and every band is placed by its
   own wavelength, so the picture cannot disagree with the numbers. */
