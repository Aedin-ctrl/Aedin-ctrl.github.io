/* ===== THE REACTION ITSELF -- 2 phenols + 1 oxygen -> 2 quinones =======
   It starts in RUN and it never stops again: later beats draw it smaller,
   but they do not pause it. `rate` is steps per second. */
function reactionCount(M,t0,rate){ return Math.max(0,Math.floor((M-t0)*(rate||0.55))); }
function reactionRun(M,t0,rate,x,y){
  const n=reactionCount(M,t0,rate);
  const ph=n*PH_PER_O2, ox=n;
  const u=((M-t0)*(rate||0.55))%1;
  /* the two phenols and the one oxygen walking into the site, every cycle */
  for(let j=0;j<PH_PER_O2;j++){
    const a=u*1.0, sx=x-34+j*7, sy=y-22+j*9;
    tokenDraw('P',H.lerp(sx,x-6,H.ease.inOut(H.clamp(a*1.3))),
                  H.lerp(sy,y,H.ease.inOut(H.clamp(a*1.3))),0);
  }
  tokenDraw('O',H.lerp(x+34,x+7,H.ease.inOut(H.clamp(u*1.3))),
                H.lerp(y-20,y,H.ease.inOut(H.clamp(u*1.3))),0);
  /* and the two quinones leaving it */
  for(let j=0;j<2;j++){
    const a=H.clamp((u-0.55)/0.45);
    if(a<=0) continue;
    tokenDraw('Q',H.lerp(x,x-16+j*32,a), H.lerp(y,y+26,a),0);
  }
  return {n:n, ph:ph, ox:ox};
}

/* ===== THE CHAIN -- quinones linking into melanin, with no enzyme ======
   A continuous ramp, not a two-state picture: it grows link by link AND
   darkens as it lengthens, and both are functions of the clock. */
const CHAINN=11;
function chainPts(i,dy){
  return [Math.round(SQ.x+22+i*15+Math.sin(i*1.7)*4),
          Math.round(SQ.y+118+(dy||0)+Math.cos(i*1.3)*13)];
}
function chain(M,t0,rate,knocked,dy){
  const grow=H.clamp((M-t0)*(rate||0.9));
  const n=Math.min(CHAINN,Math.floor(grow*CHAINN)+1);
  for(let i=0;i<n;i++){
    if(knocked&&i===knocked.i) continue;
    const p=chainPts(i,dy);
    const dark=H.clamp(i/(CHAINN-1));
    const bob=Math.sin(M*2.1+i*0.8)*3.4;
    if(i){ const q=chainPts(i-1,dy);
      if(!(knocked&&i-1===knocked.i))
        linePix([[q[0],q[1]+bob],[p[0],p[1]+bob]],
                H.rgba(H.mix(H.mix(P.orange,P.earth,dark),P.ink,0.22)),2); }
    diamondPix(p[0],p[1]+bob,4,
      H.rgba(H.mix(H.mix(P.orange,P.earth,dark),P.ink,0.10)));
  }
  return n;
}

