/* ===== #014 -- WHY NO STRAW WORKS PAST 10 METRES =====
   The piece. The format is cathode-lib.js; what needs both is cathode-run.js.

   The folk answer is that you suck water up a straw. You do not: sucking is not
   a force you can apply to a liquid. You lower the pressure above it, and the
   atmosphere -- already pressing on the whole lake at 101 kPa -- pushes the
   water up into the space you made. So the height is not set by how hard you
   pull. It is set by how heavy the air is, and that is a fixed number.

   EVERY NUMBER HERE IS DERIVED, not quoted. The piece is one equation:

       h = P / (rho * g)

   with P = 101325 Pa (standard atmosphere, exact by definition) and
   g = 9.80665 m/s^2:

   * WATER, rho = 1000.0 kg/m^3 (nominal)  ->  h = 10.3323 m
   * MERCURY, rho = 13595.1 kg/m^3 (0 C)   ->  h =  0.76000 m = 760.0 mm

   Taking water at 999.97 (its 4 C density) instead of the nominal 1000.0 moves
   the first figure to 10.3326 and the Galileo gap from 3.09 cm to 3.06. Both
   read as 10.33 m and "three centimetres" on screen, which is what the piece
   says; the code uses 1000.0 so the mercury identity divides exactly.

   760 mm falls straight out. It is not rounded to fit the barometer; the
   barometer's number IS the straw's number divided by the density ratio,
   13595.1/1000 = 13.5951. That identity is the spine of the piece and it is
   checkable with a calculator, which is why this subject was built and the
   glass-flow subject was not.

   * GALILEO. Asked about the Tuscan well diggers' wall, he blamed the WATER --
     Two New Sciences (1638) has the column breaking under its own weight at
     thirty four feet. 34 ft = 10.3632 m against the derived 10.3323 m: he was
     off by 3.1 cm, 0.30%. Right number, wrong reason. At 28 px/m that gap is
     0.86 of a pixel, so the piece does NOT draw two lines -- it draws one line
     with both numbers on it and says so. A 1px lie would be the easy version.

   * BOILING. The top of the column is nearly a vacuum, and water boils at room
     temperature in a vacuum, so 10.33 is unreachable. With p_vap = 2339 Pa at
     20 C and rho = 998.2: (101325-2339)/(998.2*9.80665) = 10.11 m.

   * ALTITUDE. The barometric formula at 1609 m gives 83.4 kPa, so Denver's
     ceiling is 8.52 m. The ceiling is not a constant of nature; it is a local
     reading, and that is the honest end of the argument.

   NOT IN THE PIECE, on purpose: the siphon. IDEAS.md #12 had it as a leg, but
   the mechanism is contested -- Hughes argues gravity plus liquid cohesion
   rather than atmospheric pressure, and siphons have been run in high vacuum.
   A contested mechanism cannot carry a leg. See v15-lift/RESEARCH.md.

   ONE INSTRUMENT. A single vertical column, drawn by column() and then
   re-measured -- the same discipline as #013's split bar. Each beat changes
   exactly one thing about it: how high the fluid stands, which fluid is in it,
   or how many ceilings are marked on it. The sameness is the argument.
*/
