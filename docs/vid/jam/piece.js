/* ===== #014 -- WHY IS THERE A TRAFFIC JAM WITH NOTHING IN FRONT OF IT? =====
   The piece. The format is cathode-lib.js; what needs both is cathode-run.js.

   Sugiyama et al. put 22 cars on a 230 m circular track and asked the drivers
   to hold about 30 km/h at a fixed distance. There was no junction, no signal,
   no obstacle and nobody misbehaving, and a jam formed anyway -- then did the
   thing a blockage cannot: while every car in it drove forwards, the jam itself
   travelled BACKWARDS, at roughly 20 km/h, which is the speed a jam crawls back
   up a real motorway. (New Journal of Physics 10 (2008) 033001, open access.)

   THE JAM ON SCREEN IS NOT ANIMATED. It is simulated, once, at load, by a car-
   following model, and the drawing reads the result. Nothing about the jam's
   shape, speed or direction was chosen by hand -- if the model did not jam,
   there would be no piece.

   THE MODEL is the Intelligent Driver Model, and it is the second one tried.
   The optimal-velocity model (which Sugiyama used) CRASHED CARS at every
   parameter set tested, and the headway wrap guard `if(h<0) h+=L` silently
   turned each collision into 230 metres of open road -- a guard converting an
   impossible state into a plausible-looking one, which is this project's most
   familiar bug. IDM cannot collide: its interaction term diverges as the gap
   closes. Positions are kept MONOTONIC rather than modulo, so a headway is
   never a wrapped quantity and a collision cannot hide as a gap.

   PARAMETERS, and what each one is answerable to:

     N=22, L=230 m          the experiment
     CAR=5.5 m              effective vehicle length
     a=1.3, b=2.5 m/s^2     acceleration, comfortable braking
     v0=14 m/s              desired free speed (never reached at this density)
     s0=1.6 m               minimum standstill gap
     T=0.364 s              time headway -- SOLVED, not chosen, so that the
                            uniform solution comes out at exactly 30.00 km/h

   What that produces, all measured from the simulation and not asserted:

     * equilibrium               30.00 km/h   (experiment: "about 30")
     * jam travels               -17.1 km/h   (experiment: "roughly 20" backward)
     * smallest gap over 600 s     1.07 m     (so: no collisions, ever)
     * the fix: a real gap +
       one steady car            14 stopped -> 0, spread 10.7 -> 3.1 m/s
     * the gap WITHOUT the
       steady car                14 stopped -> 10  (so both are needed)

   The backward speed is 17 against a measured "roughly 20" -- the paper's own
   hedge, and the wider literature gives 10-20, 15+-5 and 15-25 depending on
   road and drivers. Same sign, same order, inside the spread. The animation is
   also TIME-COMPRESSED, at ONE CONSTANT 2.5x, so no speed should be read off
   the screen; the 20 on screen is the experiment's measurement.

   One car in twenty-two CANNOT damp this jam on its own, and the piece no
   longer says it can. Car length 4.0-5.6 m was swept against headway
   0.30-1.05 s: every combination with a 30 km/h equilibrium on a 230 m ring
   leaves the speed spread essentially unchanged. 22 cars of 5.5 m is 53% metal,
   which forces a 0.364 s headway, which is too deep into the unstable regime
   for one vehicle to stabilise. Stern's damping ring was sparser than
   Sugiyama's jamming ring, and this piece shows Sugiyama's. So the FIX beat is
   about the thing the model DOES support: the gap.
*/
