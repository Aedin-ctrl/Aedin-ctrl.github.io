/* ---- the score. Every key is from the closed bank:
   click snap open blip knock tag draw zap mos crack crumble splash sub buzz
   moo note bass -- an invented name is a beat with no sound on it, and the
   only signal is the render printing "(1 failed)". ---- */
function buildScore(){
  const E=[],add=(t,k,n)=>E.push({t:+t.toFixed(3),k,n});
  const w=(n,i)=>VO[n].t[i];
  add(0.05,'open');
  PTRACK.forEach(q=>{ if(q.c) add(q.t,'click'); });
  RINGS.forEach(q=>add(q.t,'click'));
  add(BEAT.ROCK.sc-0.35,'open'); add(BEAT.END.sc-0.30,'open');
  const LAST=VO.length-1;
  add(VO[LAST].z+0.30,'snap'); add(VO[LAST].z+0.52,'click'); add(VO[LAST].z+0.67,'open');
  [2,3,4,5,6,7,8,9,11,12,13,14].forEach(n=>VO[n].t.forEach((tt,i)=>add(tt,'blip',i)));
  // the cold open: the room settles onto the rock
  const okT=VO[0].z+0.52;
  add(okT,'snap');
  add(okT+0.72,'sub');
  for(let i=0;i<7;i++) add(okT+0.80+i*0.21,'crumble',i%4);
  for(let i=0;i<9;i++) add(okT+0.95+i*0.17,'click');
  // ROCK / METEOR
  add(w(1,4),'draw'); add(w(2,2),'knock',0); add(w(2,10),'knock',1);
  add(w(3,8),'sub'); add(w(3,12),'draw');
  // CLOCK / START
  for(let i=0;i<8;i++) add(w(4,4)+i*0.30,'blip',i%3);
  add(w(5,2),'zap'); add(w(6,4),'draw'); add(w(6,13),'tag');
  // DIRT
  for(let i=0;i<4;i++) add(w(7,7)+i*0.36,'knock',i%3);
  // BLANK -- the shot
  add(w(8,2),'draw'); add(w(8,13),'zap'); add(w(8,13)+0.06,'tag'); add(w(8,13)+0.12,'sub');
  add(w(9,2),'mos'); add(w(9,10),'zap'); add(w(9,10)+0.06,'tag');
  // CLEAN
  for(let i=0;i<4;i++) add(w(10,2)+0.30+i*0.52,'click');
  add(w(10,2),'draw');
  add(w(11,0),'draw'); add(w(11,4),'zap'); add(w(11,4)+0.06,'tag');
  // TURN
  add(w(12,1),'draw'); add(w(13,1),'draw');
  add(w(13,13),'knock',1); add(w(13,15),'zap'); add(w(13,15)+0.06,'tag');
  add(w(14,2),'crumble',2);
  for(const k in BEAT) if(BEAT[k].sc>0) add(BEAT[k].sc,'mos');
  const BPM=88, E8=30/BPM, FIG=[146.83,174.61,196.00,174.61,164.81,196.00,146.83,130.81];
  for(let i=0,tt=BEAT.ROCK.sc;tt<VO[VO.length-2].t[0];i++,tt+=E8){
    add(tt,'note',FIG[i%FIG.length]*((i%16)<8?1:1.5));
    if(i%8===0) add(tt,'bass',FIG[0]/2);
  }
  E.sort((a,b)=>a.t-b.t); return E;
}
