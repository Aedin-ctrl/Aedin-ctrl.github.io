  // MELT -- the tug that fails
  add(w(2,7),'draw'); add(w(2,13),'zap'); add(w(2,18),'tag');
  // BURN -- carbon down the throat, CO out
  add(w(3,3),'draw'); add(w(3,10),'zap'); add(w(4,8),'draw'); add(w(4,13),'tag');
