  add(w(9,8),'zap'); add(w(10,2),'draw'); add(w(11,9),'tag');
  // SLICE -- the saw
  add(w(13,2),'draw'); add(w(13,6),'draw');
  for(const k in BEAT) if(BEAT[k].sc>0) add(BEAT[k].sc,'mos');
