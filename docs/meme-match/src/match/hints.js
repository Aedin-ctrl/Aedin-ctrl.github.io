// worst = { name, value, mu, d } from scoreTemplate; returns '' when nothing is notably off.
export function hintFor(worst) {
  if (!worst || Math.abs(worst.d) < 0.8) return '';
  const base = worst.name.replace(/^h[01]_/, '').replace(/^arm[LR]_/, '');
  const pair = H[base] || H[worst.name];
  if (!pair) return '';
  return (worst.value < worst.mu ? pair[0] : pair[1]) || '';
}
