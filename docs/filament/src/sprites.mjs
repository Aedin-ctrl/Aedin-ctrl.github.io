// Sprite data, written as rows of palette ENTRIES, not colours.
//
// '0' is transparent (or the backdrop), and 1-3 are the three entries of whichever sub-palette the
// draw call names. That is why the same eight bytes can be a person in daylight, a silhouette at
// night, and a white flash for two frames — nothing here knows what colour it is.

const spr = (...rows) => rows.map((r) => [...r].map(Number));

